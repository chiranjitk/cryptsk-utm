/**
 * POST /api/v1/interfaces/apply — converge ONE host interface onto the
 * console DB (single-interface by design — no bulk exec path).
 *
 * Two-phase (enterprise commit semantics):
 *   1. plan  — pure buildApplyPlan() output (always returned)
 *   2. exec  — only when CONSOLE_OS_APPLY=1 AND `ip` exists on the host AND
 *              every command passes the iproute2 whitelist; otherwise the
 *              response carries the plan + an honest reason.
 *
 * Body { name } — required, narrows the run to one interface.
 */

import { z } from "zod";
import { route } from "@/lib/api/handler";
import { loadShapedIfaces, parseIfaceConfig } from "@/lib/network/iface-service";
import { buildApplyPlan, osRowFor, type OsPlan } from "@/lib/network/iface-os";
import { readInterfaces } from "@/lib/host/proc";
import { hasTool, runTool } from "@/lib/host/tools";
import type { IfaceRuleView } from "@/lib/network/iface-rules";

export const dynamic = "force-dynamic";

const applyBodySchema = z.object({ name: z.string().min(1).max(64) });

/** Only iproute2 link/addr/route verbs generated by buildApplyPlan may exec. */
const EXEC_WHITELIST = /^ip (link|addr|route) [a-z0-9].*$/;

export const POST = route(
  { area: "network", bodySchema: applyBodySchema, section: "interfaces" },
  async ({ auth, body }) => {
    const [shaped, osIfaces] = await Promise.all([loadShapedIfaces(auth.tenantId), readInterfaces()]);

    const shapedRow = shaped.find((i) => i.name === body.name);
    if (!shapedRow) {
      return {
        data: {
          applied: false,
          reason: `Interface '${body.name}' not found`,
          plans: [],
        },
      };
    }
    const view: IfaceRuleView = {
      id: shapedRow.id,
      name: shapedRow.name,
      type: shapedRow.type,
      mode: shapedRow.mode,
      role: shapedRow.role,
      mtu: shapedRow.mtu,
      mssClamp: shapedRow.mssClamp,
      enabled: shapedRow.enabled,
      parentName: shapedRow.parentName,
      vlanId: shapedRow.vlanId,
      config: parseIfaceConfig(JSON.stringify(shapedRow.config)),
    };

    const plan: OsPlan = buildApplyPlan(view, osRowFor(osIfaces, view.name));
    const plans = [plan];
    const applyEnabled = process.env.CONSOLE_OS_APPLY === "1";

    if (!applyEnabled) {
      return {
        data: {
          applied: false,
          reason: "OS apply is gated off on this installation (CONSOLE_OS_APPLY!=1) — plan preview only",
          plans,
        },
        audit: {
          action: "iface.os-apply.plan",
          objectType: "interface",
          objectName: body.name,
        },
      };
    }

    const toolPresent = await hasTool("ip");
    if (!toolPresent) {
      return {
        data: {
          applied: false,
          reason: "'ip' (iproute2) not found on the host — cannot execute the plan",
          plans,
        },
        audit: {
          action: "iface.os-apply.plan",
          objectType: "interface",
          objectName: body.name,
        },
      };
    }

    // whitelist gate — any step not matching the iproute2 grammar aborts the run
    const rejected = plan.steps.filter((s) => !EXEC_WHITELIST.test(s.cmd));
    if (rejected.length > 0) {
      return {
        data: {
          applied: false,
          reason: `${rejected.length} plan step(s) failed the iproute2 whitelist — execution aborted`,
          plans,
        },
        audit: {
          action: "iface.os-apply.exec",
          objectType: "interface",
          objectName: body.name,
          result: "denied",
        },
      };
    }

    const results: Array<{ cmd: string; ok: boolean; stderr?: string }> = [];
    for (const step of plan.steps) {
      const r = await runTool(step.cmd);
      results.push({ cmd: step.cmd, ok: r.ok, stderr: r.ok ? undefined : r.stderr });
      if (!r.ok) break; // transactional: stop at first failure (rollback is P1)
    }
    const failed = results.filter((r) => !r.ok);

    return {
      data: {
        applied: failed.length === 0,
        reason: failed.length === 0 ? "plan executed" : `${failed.length} step(s) failed`,
        results,
        plans,
      },
      audit: {
        action: "iface.os-apply.exec",
        objectType: "interface",
        objectName: body.name,
      },
    };
  },
);
