// ── IPv6 math helpers (pure) ────────────────────────────────────────────────

/** BigInt → canonical compressed lowercase IPv6 address ("fd00:60::"). */
export function ipv6BigIntToAddr(value: bigint): string {
  const groups: string[] = [];
  for (let i = 7; i >= 0; i--) {
    groups.push(((value >> BigInt(i * 16)) & 0xffffn).toString(16));
  }
  // compress the LONGEST run of ≥2 zero groups
  let bestStart = -1;
  let bestLen = 0;
  let curStart = -1;
  let curLen = 0;
  groups.forEach((g, i) => {
    if (g === "0") {
      if (curStart < 0) curStart = i;
      curLen += 1;
      if (curLen > bestLen) {
        bestStart = curStart;
        bestLen = curLen;
      }
    } else {
      curStart = -1;
      curLen = 0;
    }
  });
  if (bestLen < 2) return groups.join(":");
  const head = groups.slice(0, bestStart).join(":");
  const tail = groups.slice(bestStart + bestLen).join(":");
  return `${head}::${tail}`;
}

/** Mask host bits → "subnet/prefixLen" CIDR (null on invalid input). */
export function ipv6SubnetCidr(addr: string, prefixLen: number): string | null {
  const v = ipv6ToBigInt(addr);
  if (v === null || prefixLen < 0 || prefixLen > 128) return null;
  const hostBits = BigInt(128 - prefixLen);
  const network = prefixLen === 0 ? 0n : (v >> hostBits) << hostBits;
  return `${ipv6BigIntToAddr(network)}/${prefixLen}`;
}

/** First /64 of the pool's subnet — the prefix radvd advertises. */
export function radvdPrefix64(poolStart: string): string | null {
  return ipv6SubnetCidr(poolStart, 64);
}

function safeIface(name: string): string {
  const s = name.replace(/[^A-Za-z0-9._@:-]/g, "").slice(0, 32);
  return s || "unknown-iface";
}

// ── kea-dhcp6.conf renderer (full-file, keepalived-style) ───────────────────

export interface Kea6SubnetView {
  id: number;
  subnet: string;
  iface: string;
  pool: string;
}

/**
 * Full /etc/kea/kea-dhcp6.conf. Deterministic: identical DB state →
 * byte-identical file (hash-stable). When dhcpv6 is disabled or no enabled
 * server exists the config is a minimal VALID empty config (kea -t accepts an
 * empty subnet6 list) and the plan stops the service.
 */
export function renderKea6Conf(
  input: Ipv6OsInput,
): { text: string; subnets: Kea6SubnetView[]; enabledServers: Dhcpv6ServerInput[] } {
  const serving = input.settings.enabled && input.settings.dhcpv6Enabled;
  const enabledServers = serving ? input.servers.filter((s) => s.enabled) : [];

  const interfaces = [...new Set(enabledServers.map((s) => safeIface(s.interfaceName)))].sort();
  const validLifetime =
    enabledServers.length > 0
      ? Math.min(...enabledServers.map((s) => Math.max(60, Math.floor(s.validLifetimeSec))))
      : 3600;

  const subnetEntries: Array<Record<string, unknown>> = [];
  const subnets: Kea6SubnetView[] = [];
  for (const s of enabledServers) {
    const subnet = ipv6SubnetCidr(s.poolStart, s.prefixLength) ?? `${s.poolStart}/${s.prefixLength}`;
    const optionData: Array<Record<string, unknown>> = [];
    if (s.dnsServers.length > 0) {
      optionData.push({ name: "domain-name-servers", data: s.dnsServers.join(", ") });
    }
    const domains = (s.domainSearch ?? "")
      .split(",")
      .map((d) => d.trim())
      .filter(Boolean);
    if (domains.length > 0) {
      optionData.push({ name: "domain-search", data: domains.join(", ") });
    }
    const entry: Record<string, unknown> = {
      id: MANAGED_ID_BASE + s.id,
      subnet,
      interface: safeIface(s.interfaceName),
      pools: [{ pool: `${s.poolStart} - ${s.poolEnd}` }],
    };
    if (optionData.length > 0) entry["option-data"] = optionData;
    entry["user-context"] = { [MANAGED_MARKER]: true };
    subnetEntries.push(entry);
    subnets.push({ id: s.id, subnet, iface: safeIface(s.interfaceName), pool: `${s.poolStart} - ${s.poolEnd}` });
  }

  const doc: Record<string, unknown> = {
    Dhcp6: {
      "interfaces-config": { interfaces },
      "lease-database": { type: "memfile", persist: true },
      "valid-lifetime": validLifetime,
      "subnet6": subnetEntries,
      "user-context": { [MANAGED_MARKER]: true },
    },
  };

  const L: string[] = [MANAGED_HEADER];
  if (subnetEntries.length === 0) {
    L.push("# DHCPv6 disabled in console (or no enabled server) — kea-dhcp6-server is stopped on apply.");
  } else {
    L.push(
      `# ${subnetEntries.length} managed subnet6 entry(ies), id = ${MANAGED_ID_BASE} + db id — applied via kea-dhcp6 -t → systemctl restart ${KEA6_SERVICE}`,
    );
  }
  L.push(JSON.stringify(doc, null, 2));
  return { text: L.join("\n") + "\n", subnets, enabledServers };
}

/**
 * Parse kea6 conf text — the renderer writes a `#` comment header (Kea's
 * config parser accepts `#`/`//` comments) so a plain JSON.parse would choke;
 * full-line `#` comments are stripped first. Throws ApiError.validation on a
 * non-Dhcp6 document (operator edited it badly) — the plan is then refused.
 */
export function parseKea6Conf(text: string): { Dhcp6?: Record<string, unknown> } {
  const stripped = text
    .split("\n")
    .filter((l) => !l.trimStart().startsWith("#"))
    .join("\n");
  let doc: unknown;
  try {
    doc = JSON.parse(stripped);
  } catch {
    throw ApiError.validation(
      "Live kea-dhcp6.conf is not a valid Dhcp6 JSON document — refusing to overwrite it (fix or remove the file first)",
      {},
    );
  }
  if (!doc || typeof doc !== "object" || (doc as Record<string, unknown>)["Dhcp6"] === undefined) {
    throw ApiError.validation("Live kea-dhcp6.conf has no Dhcp6 section — refusing to overwrite it", {});
  }
  return doc as { Dhcp6?: Record<string, unknown> };
}

/** True when a JSON subnet6 entry carries the console managed marker. */
export function isManagedKea6Subnet(entry: Record<string, unknown>): boolean {
  const uc = entry["user-context"];
  if (!uc || typeof uc !== "object") return false;
  return (uc as Record<string, unknown>)[MANAGED_MARKER] === true;
}

/** Managed subnet6 ids currently in the live conf (drift per-server truth). */
export function liveKea6ManagedIds(doc: { Dhcp6?: Record<string, unknown> }): number[] {
  const list = Array.isArray(doc.Dhcp6?.["subnet6"])
    ? (doc.Dhcp6!["subnet6"] as Array<Record<string, unknown>>)
    : [];
  const ids: number[] = [];
  for (const entry of list) {
    const id = Number(entry["id"]);
    if (Number.isFinite(id) && (isManagedKea6Subnet(entry) || id >= MANAGED_ID_BASE)) ids.push(id);
  }
  return ids;
}

// ── radvd.conf renderer (full-file, keepalived-style) ───────────────────────

export interface RadvdIfaceView {
  iface: string;
  prefix: string;
  mode: RaMode;
}

/**
 * /etc/radvd.conf from raMode. RA advertises on LAN interfaces — the enabled
 * Dhcpv6Server rows own the interface list (one stanza per interface, the
 * first enabled server on that iface wins its /64 prefix; the prefix is
 * derived from poolStart with /64 — NEVER pdWanInterface).
 *
 *   disabled      → empty conf + `systemctl stop radvd` (no -c validation —
 *                   radvd rejects a conf without interface stanzas)
 *   router_only   → AdvSendAdvert on, managed/other off, prefix autonomous OFF
 *   slaac         → AdvAutonomous on, managed/other off
 *   slaac_dhcpv6  → AdvManagedFlag on + AdvOtherConfigFlag on + AdvAutonomous on
 *   rdnssEnabled  → RDNSS <dns servers> stanza inside each interface
 *
 * radvd 2.20 configtest: `radvd -c [configpath]` — exits >0 on a bad conf.
 */
export function renderRadvdConf(
  input: Ipv6OsInput,
): { text: string; ifaces: RadvdIfaceView[]; warnings: string[] } {
  const warnings: string[] = [];
  const L: string[] = [MANAGED_HEADER];
  const raActive = input.settings.enabled && input.settings.raMode !== "disabled";
  L.push(`# console section: ipv6 · RA mode: ${input.settings.raMode}`);

  if (!raActive) {
    L.push("# RA disabled in console — radvd service is stopped on apply.");
    return { text: L.join("\n") + "\n", ifaces: [], warnings };
  }

  const mode = input.settings.raMode;
  const seen = new Map<string, Dhcpv6ServerInput>();
  for (const s of input.servers) {
    if (!s.enabled) continue;
    if (!seen.has(s.interfaceName)) seen.set(s.interfaceName, s);
    else
      warnings.push(
        `interface ${s.interfaceName}: multiple DHCPv6 servers — RA stanza rendered from server #${seen.get(s.interfaceName)!.id} only`,
      );
  }

  const ifaces: RadvdIfaceView[] = [];
  for (const [ifaceName, s] of [...seen.entries()].sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
    const prefix = radvdPrefix64(s.poolStart);
    if (!prefix) {
      warnings.push(`interface ${ifaceName}: pool start ${s.poolStart} is not a valid IPv6 address — no prefix advertised`);
      continue;
    }
    ifaces.push({ iface: safeIface(ifaceName), prefix, mode });
    L.push("");
    L.push(`interface ${safeIface(ifaceName)} {`);
    L.push("\tAdvSendAdvert on;");
    L.push("\tMinRtrAdvInterval 30;");
    L.push("\tMaxRtrAdvInterval 100;");
    L.push(`\tAdvManagedFlag ${mode === "slaac_dhcpv6" ? "on" : "off"};`);
    L.push(`\tAdvOtherConfigFlag ${mode === "slaac_dhcpv6" ? "on" : "off"};`);
    L.push("\tprefix " + prefix + " {");
    L.push("\t\tAdvOnLink on;");
    L.push(`\t\tAdvAutonomous ${mode === "router_only" ? "off" : "on"};`);
    L.push("\t};");
    if (input.settings.rdnssEnabled && s.dnsServers.length > 0) {
      L.push(`\tRDNSS ${s.dnsServers.map((d) => d.trim()).join(" ")} {`);
      L.push("\t\tAdvRDNSSLifetime 600;");
      L.push("\t};");
    }
    L.push("};");
  }
  if (ifaces.length === 0) {
    L.push("");
    L.push("# No enabled DHCPv6 server interface with a usable pool — nothing advertised.");
    L.push("# radvd stays stopped until a server is enabled (see DHCPv6 servers table).");
  }
  return { text: L.join("\n") + "\n", ifaces, warnings };
}

// ── NAT66 nft renderer (dedicated inet utm_nat66 table) ─────────────────────

export interface Nat66Statement {
  id: number;
  hook: "prerouting" | "postrouting";
  line: string;
}

/**
 * One nft statement per NAT66 rule (comments `nat66:<id>:<name>` give the
 * rules a stable identity for drift + counters):
 *   nptv6         → prerouting `dnat ip6 saddr <S> prefix <T>` (stateless) +
 *                   postrouting reverse `snat ip6 daddr <T> prefix <S>`
 *   masquerade66  → postrouting `[ip6 saddr <S>] oifname "<iface>" masquerade`
 *   dnat66        → prerouting `dnat ip6 daddr <S> to <T>`; with destPort the
 *                   port-restricted form renders a tcp + a udp leg
 * (nft ≥ 0.9.3 syntax; `nft -c -f` on the appliance is the final authority.)
 */
export function nat66Statements(rules: Nat66RuleInput[]): { statements: Nat66Statement[]; warnings: string[] } {
  const statements: Nat66Statement[] = [];
  const warnings: string[] = [];
  for (const r of rules) {
    if (!r.enabled) continue;
    const comment = `nat66:${r.id}:${r.name.replace(/"/g, "").slice(0, 40)}`;
    if (r.type === "nptv6") {
      const s = r.sourcePrefix?.trim();
      const t = r.translatedPrefix?.trim();
      if (!s || !t) {
        warnings.push(`nat66 #${r.id} (${r.name}): nptv6 without source/translated prefix — excluded`);
        continue;
      }
      const sLen = Number(s.split("/")[1]);
      const tLen = Number(t.split("/")[1]);
      if (Number.isFinite(sLen) && Number.isFinite(tLen) && sLen !== tLen) {
        warnings.push(`nat66 #${r.id} (${r.name}): nptv6 prefix lengths differ (/${sLen} → /${tLen}) — NPTv6 requires equal lengths`);
      }
      statements.push({ id: r.id, hook: "prerouting", line: `dnat ip6 saddr ${s} prefix ${t} comment ${JSON.stringify(comment)}` });
      statements.push({ id: r.id, hook: "postrouting", line: `snat ip6 daddr ${t} prefix ${s} comment ${JSON.stringify(comment)}` });
      continue;
    }
    if (r.type === "masquerade66") {
      const src = r.sourcePrefix?.trim();
      const match = [src ? `ip6 saddr ${src}` : "", `oifname ${JSON.stringify(safeIface(r.interfaceName))}`]
        .filter(Boolean)
        .join(" ");
      statements.push({ id: r.id, hook: "postrouting", line: `${match} masquerade comment ${JSON.stringify(comment)}` });
      continue;
    }
    // dnat66 — sourcePrefix matches the EXTERNAL destination prefix
    const s = r.sourcePrefix?.trim();
    const t = r.translatedPrefix?.trim();
    if (!s || !t) {
      warnings.push(`nat66 #${r.id} (${r.name}): dnat66 without source/translated prefix — excluded`);
      continue;
    }
    const port = r.destPort;
    if (port != null && Number.isInteger(port) && port > 0 && port < 65536) {
      statements.push({ id: r.id, hook: "prerouting", line: `tcp dport ${port} dnat ip6 daddr ${s} to ${t} comment ${JSON.stringify(comment)}` });
      statements.push({ id: r.id, hook: "prerouting", line: `udp dport ${port} dnat ip6 daddr ${s} to ${t} comment ${JSON.stringify(comment)}` });
    } else {
      statements.push({ id: r.id, hook: "prerouting", line: `dnat ip6 daddr ${s} to ${t} comment ${JSON.stringify(comment)}` });
    }
  }
  return { statements, warnings };
}

/** Full nat66 nft file — atomic replace of the console table ONLY. */
export function renderNat66Nft(rules: Nat66RuleInput[]): {
  text: string;
  statements: Nat66Statement[];
  warnings: string[];
} {
  const { statements, warnings } = nat66Statements(rules);
  const pre = statements.filter((s) => s.hook === "prerouting");
  const post = statements.filter((s) => s.hook === "postrouting");
  const L: string[] = [
    "#!/usr/sbin/nft -f",
    `# ${NAT66_TABLE_NAME} — managed by the Cryptsk console (GUI: Network → IPv6 → Apply to OS)`,
    "#",
    "# Atomic replace of the console-managed table ONLY — never flushes the",
    "# entire ruleset: console-firewall, fail2ban and foreign tables survive.",
    "",
    `destroy table ${NAT66_TABLE}`,
    "",
    `table ${NAT66_TABLE} {`,
    "\tchain prerouting {",
    "\t\ttype nat hook prerouting priority dstnat; policy accept;",
  ];
  for (const s of pre) L.push(`\t\t${s.line}`);
  if (pre.length === 0) L.push("\t\t# no prerouting nat66 rules");
  L.push("\t}");
  L.push("");
  L.push("\tchain postrouting {");
  L.push("\t\ttype nat hook postrouting priority srcnat; policy accept;");
  for (const s of post) L.push(`\t\t${s.line}`);
  if (post.length === 0) L.push("\t\t# no postrouting nat66 rules");
  L.push("\t}");
  L.push("}");
  return { text: L.join("\n") + "\n", statements, warnings };
}

/** Extract the normalized `table inet utm_nat66` block lines (comments + counters stripped). */
export function extractNat66TableBlock(source: string): string[] {
  const lines: string[] = [];
  let inside = false;
  let depth = 0;
  for (const raw of source.split("\n")) {
    const line = raw.replace(/#.*$/, "").trim();
    if (!inside) {
      if (new RegExp(`^table ${NAT66_TABLE}\\s*\\{`).test(line)) {
        inside = true;
        depth = 1;
      }
      continue;
    }
    depth += (line.match(/\{/g) ?? []).length - (line.match(/\}/g) ?? []).length;
    if (depth <= 0) break;
    const norm = line
      .replace(/counter packets \d+ bytes \d+/g, "")
      .replace(/comment "[^"]*"/g, "")
      .replace(/\s+/g, " ")
      .trim();
    if (norm) lines.push(norm);
  }
  return lines;
}

/** Pure compare of generated vs live nat66 table bodies (unit-testable). */
export function nat66BlocksInSync(genFile: string, liveDump: string): boolean {
  const a = extractNat66TableBlock(genFile);
  const b = extractNat66TableBlock(liveDump);
  if (b.length === 0) return false;
  return a.length === b.length && a.every((l, i) => l === b[i]);
}

// ── cross-field validation (BEFORE any file write — dhcp4 pattern) ──────────

/** Pool inside subnet, start<end, duplicate subnets. Mirrors validateSubnetInputs. */
export function validateIpv6Inputs(input: Ipv6OsInput): string[] {
  const problems: string[] = [];
  const enabled = input.settings.enabled && input.settings.dhcpv6Enabled ? input.servers.filter((s) => s.enabled) : [];
  const seenSubnets = new Map<string, number>();
  for (const s of enabled) {
    const start = ipv6ToBigInt(s.poolStart);
    const end = ipv6ToBigInt(s.poolEnd);
    if (start === null) problems.push(`server #${s.id} (${s.interfaceName}): pool start ${s.poolStart} is not a valid IPv6 address`);
    if (end === null) problems.push(`server #${s.id} (${s.interfaceName}): pool end ${s.poolEnd} is not a valid IPv6 address`);
    if (start !== null && end !== null && end <= start) {
      problems.push(`server #${s.id} (${s.interfaceName}): pool end must be greater than pool start`);
    }
    if (s.prefixLength !== 64 && s.prefixLength !== 128) {
      problems.push(`server #${s.id} (${s.interfaceName}): unsupported prefixLength ${s.prefixLength} (64|128 only)`);
    }
    const subnet = ipv6SubnetCidr(s.poolStart, s.prefixLength);
    if (subnet && start !== null) {
      const [net] = subnet.split("/");
      const netV = ipv6ToBigInt(net);
      if (netV !== null) {
        const offset = start - netV;
        const hostBits = BigInt(128 - s.prefixLength);
        const max = (1n << hostBits) - 1n;
        if (offset > max) problems.push(`server #${s.id} (${s.interfaceName}): pool start ${s.poolStart} is outside ${subnet}`);
        if (end !== null && end - netV > max) problems.push(`server #${s.id} (${s.interfaceName}): pool end ${s.poolEnd} is outside ${subnet}`);
      }
      const owner = seenSubnets.get(subnet);
      if (owner !== undefined) {
        problems.push(`subnet ${subnet} is declared by both server #${owner} and #${s.id} — Kea refuses duplicate subnet6 entries`);
      } else {
        seenSubnets.set(subnet, s.id);
      }
    }
  }
  return problems;
}

// ── apply plan ──────────────────────────────────────────────────────────────

export type Ipv6StepKind =
  | "dir"
  | "backup"
  | "write"
  | "validate"
  | "install"
  | "restart"
  | "stop"
  | "sysctl"
  | "probe"
  | "cleanup";

export interface Ipv6OsStep {
  step: string;
  cmd: string;
  kind: Ipv6StepKind;
  /** probes / cleanup — failure recorded, no rollback */
  optional?: boolean;
}

export interface Ipv6OsFile {
  path: string;
  content: string;
  kind: "kea6" | "radvd" | "nat66";
}

export interface Ipv6OsPlan {
  mode: "exec" | "plan";
  steps: Ipv6OsStep[];
  files: Ipv6OsFile[];
  keaSubnets: Kea6SubnetView[];
  radvdIfaces: RadvdIfaceView[];
  nat66Statements: Nat66Statement[];
  skipped: Array<{ name: string; reason: string }>;
  reasons: string[];
  warnings: string[];
  refused: string | null;
  backupDir: string;
  /** live service pre-states (executor rollback target) */
  preState: { keaRunning: boolean; radvdRunning: boolean };
  keaStageFile: string;
  radvdStageFile: string;
  nat66File: string;
  keaChanged: boolean;
  radvdChanged: boolean;
  nat66Changed: boolean;
  sysctlNeeded: boolean;
  keaServiceWanted: "active" | "stopped";
  radvdServiceWanted: "active" | "stopped";
  confHash: string;
  radvdHash: string;
  nat66Hash: string;
  guarded: boolean;
  /** nothing to converge at all (byte-identical + services in wanted state) */
  empty: boolean;
}

export function keaServiceWanted(input: Ipv6OsInput): "active" | "stopped" {
  const serving = input.settings.enabled && input.settings.dhcpv6Enabled && input.servers.some((s) => s.enabled);
  return serving ? "active" : "stopped";
}

export function radvdServiceWanted(input: Ipv6OsInput): "active" | "stopped" {
  const adv = input.settings.enabled && input.settings.raMode !== "disabled" && input.servers.some((s) => s.enabled);
  return adv ? "active" : "stopped";
}

export function sysctlNeededFor(input: Ipv6OsInput): boolean {
  return input.settings.enabled && (input.settings.dhcpv6Enabled || input.settings.raMode !== "disabled");
}

function refusedPlan(mode: "exec" | "plan", ts: string, reasons: string[]): Ipv6OsPlan {
  return {
    mode,
    steps: [],
    files: [],
    keaSubnets: [],
    radvdIfaces: [],
    nat66Statements: [],
    skipped: [],
    reasons,
    warnings: [],
    refused: reasons[0] ?? "refused",
    backupDir: `${IPV6_STATE_DIR}/backup-${ts}`,
    preState: { keaRunning: false, radvdRunning: false },
    keaStageFile: KEA6_STAGE_FILE,
    radvdStageFile: RADVD_STAGE_FILE,
    nat66File: `${IPV6_STATE_DIR}/nat66-${ts}.nft`,
    keaChanged: false,
    radvdChanged: false,
    nat66Changed: false,
    sysctlNeeded: false,
    keaServiceWanted: "stopped",
    radvdServiceWanted: "stopped",
    confHash: "",
    radvdHash: "",
    nat66Hash: "",
    guarded: true,
    empty: true,
  };
}

/**
 * Snapshot → stage → validate → install → service → sysctl → verify plan.
 * Pure: all OS reads arrive via `facts`. Sections whose rendered content is
 * byte-identical to the live file AND whose service already sits in the
 * wanted state are skipped (zero-churn — mirrors kea-dhcp4 behaviour).
 */
export function buildIpv6ApplyPlan(
  input: Ipv6OsInput,
  facts: Ipv6OsFacts,
  mode: "exec" | "plan",
  ts: string,
): Ipv6OsPlan {
  const problems = validateIpv6Inputs(input);
  if (problems.length > 0) {
    return refusedPlan(mode, ts, problems.map((p) => `refused: ${p}`));
  }

  const backupDir = `${IPV6_STATE_DIR}/backup-${ts}`;
  const steps: Ipv6OsStep[] = [];
  const skipped: Array<{ name: string; reason: string }> = [];
  const reasons: string[] = [];

  // ── renders ──
  const kea = renderKea6Conf(input);
  const radvd = renderRadvdConf(input);
  const nat66 = renderNat66Nft(input.nat66);
  const warnings = [...radvd.warnings, ...nat66.warnings];

  // ── section change decisions (zero-churn) ──
  const keaFileChanged = facts.keaConfText !== kea.text;
  const radvdFileChanged = facts.radvdConfText !== radvd.text;
  const nat66InKernel = facts.liveRuleset != null && nat66BlocksInSync(nat66.text, facts.liveRuleset);

  const keaWanted = keaServiceWanted(input);
  const radvdWanted = radvdServiceWanted(input);
  const keaServiceOk = facts.keaRunning === (keaWanted === "active");
  const radvdServiceOk = facts.radvdRunning === (radvdWanted === "active");
  const keaChanged = keaFileChanged || !keaServiceOk;
  const radvdChanged = radvdFileChanged || !radvdServiceOk;
  const nat66Changed = !nat66InKernel;
  const sysctlNeeded = sysctlNeededFor(input) && facts.sysctlForwarding !== true;

  steps.push({ step: "state dir", cmd: `mkdir -p ${IPV6_STATE_DIR}`, kind: "dir" });

  // ── backups (snapshot BEFORE any mutation; executor fs-backs up the nft dump) ──
  if (facts.keaConfPresent && keaChanged) {
    steps.push({ step: "backup kea conf", cmd: `cp ${KEA6_CONF_FILE} ${backupDir}/kea-dhcp6.conf`, kind: "backup" });
  }
  if (facts.radvdConfPresent && radvdChanged) {
    steps.push({ step: "backup radvd conf", cmd: `cp ${RADVD_CONF_FILE} ${backupDir}/radvd.conf`, kind: "backup" });
  }

  const files: Ipv6OsFile[] = [];

  // ── kea-dhcp6 section ──
  if (keaChanged) {
    steps.push({ step: "stage kea conf", cmd: `write-file ${KEA6_STAGE_FILE}`, kind: "write" });
    steps.push({ step: "validate kea conf", cmd: `kea-dhcp6 -t ${KEA6_STAGE_FILE}`, kind: "validate" });
    steps.push({ step: "install kea conf", cmd: `install -m 0644 ${KEA6_STAGE_FILE} ${KEA6_CONF_FILE}`, kind: "install" });
    steps.push({ step: "cleanup kea stage", cmd: `rm -f ${KEA6_STAGE_FILE}`, kind: "cleanup", optional: true });
    if (keaWanted === "active") {
      steps.push({ step: "restart kea-dhcp6", cmd: `systemctl restart ${KEA6_SERVICE}`, kind: "restart" });
    } else {
      steps.push({ step: "stop kea-dhcp6", cmd: `systemctl stop ${KEA6_SERVICE}`, kind: "stop" });
    }
    steps.push({
      step: "verify kea-dhcp6",
      cmd: `systemctl is-active ${KEA6_SERVICE}`,
      kind: "probe",
      ...(keaWanted === "stopped" ? { optional: true } : {}),
    });
    files.push({ path: KEA6_CONF_FILE, content: kea.text, kind: "kea6" });
  } else {
    skipped.push({ name: "kea-dhcp6.conf", reason: "rendered conf byte-identical and service already in wanted state — zero-churn" });
  }

  // ── radvd section ──
  if (radvdChanged) {
    steps.push({ step: "stage radvd conf", cmd: `write-file ${RADVD_STAGE_FILE}`, kind: "write" });
    // raMode disabled → empty conf + stop; radvd -c REJECTS a conf without
    // interface stanzas, so the configtest only runs when something is advertised.
    if (radvdWanted === "active") {
      steps.push({ step: "validate radvd conf", cmd: `radvd -c ${RADVD_STAGE_FILE}`, kind: "validate" });
    }
    steps.push({ step: "install radvd conf", cmd: `install -m 0644 ${RADVD_STAGE_FILE} ${RADVD_CONF_FILE}`, kind: "install" });
    steps.push({ step: "cleanup radvd stage", cmd: `rm -f ${RADVD_STAGE_FILE}`, kind: "cleanup", optional: true });
    if (radvdWanted === "active") {
      steps.push({ step: "restart radvd", cmd: `systemctl restart ${RADVD_SERVICE}`, kind: "restart" });
    } else {
      steps.push({ step: "stop radvd", cmd: `systemctl stop ${RADVD_SERVICE}`, kind: "stop" });
    }
    steps.push({
      step: "verify radvd",
      cmd: `systemctl is-active ${RADVD_SERVICE}`,
      kind: "probe",
      ...(radvdWanted === "stopped" ? { optional: true } : {}),
    });
    files.push({ path: RADVD_CONF_FILE, content: radvd.text, kind: "radvd" });
  } else {
    skipped.push({ name: "radvd.conf", reason: "rendered conf byte-identical and service already in wanted state — zero-churn" });
  }

  // ── NAT66 section (dedicated table — never flushes the ruleset) ──
  const nat66File = `${IPV6_STATE_DIR}/nat66-${ts}.nft`;
  if (nat66Changed) {
    steps.push({ step: "stage nat66 file", cmd: `write-file ${nat66File}`, kind: "write" });
    steps.push({ step: "validate nat66", cmd: `nft -c -f ${nat66File}`, kind: "validate" });
    steps.push({ step: "apply nat66", cmd: `nft -f ${nat66File}`, kind: "install" });
    steps.push({ step: "cleanup nat66 file", cmd: `rm -f ${nat66File}`, kind: "cleanup", optional: true });
    files.push({ path: nat66File, content: nat66.text, kind: "nat66" });
    // persistence copy (/etc/console-nft/nat66.nft + include line) is
    // fs-written by the executor — best-effort, warnings only
  } else {
    skipped.push({ name: NAT66_TABLE, reason: "kernel table in sync — zero-churn" });
  }

  // informational listener snapshot (kea-dhcp6 binds :547 — raw sockets may
  // keep it out of ss; the probe is evidence, never a failure). Only emitted
  // when a service actually converges — zero-churn stays zero-touch.
  if ((keaChanged || radvdChanged) && (keaWanted === "active" || radvdWanted === "active")) {
    steps.push({ step: "listener snapshot", cmd: "ss -ltn", kind: "probe", optional: true });
    steps.push({ step: "udp listener snapshot", cmd: "ss -lun", kind: "probe", optional: true });
  }

  // ── sysctl forwarding ──
  if (sysctlNeeded) {
    steps.push({ step: "sysctl forwarding", cmd: "sysctl -w net.ipv6.conf.all.forwarding=1", kind: "sysctl" });
    reasons.push("net.ipv6.conf.all.forwarding=1 — required for RA/DHCPv6 serving and NAT66");
  }

  // honesty notes
  if (keaWanted === "active" && !facts.keaAvailable) {
    reasons.push("kea-dhcp6 binary not found on this host — kea steps will fail honestly on exec");
  }
  if (radvdWanted === "active" && !facts.radvdAvailable) {
    reasons.push("radvd binary not found on this host — radvd steps will fail honestly on exec");
  }
  if (nat66.statements.length > 0 && !facts.nftAvailable) {
    reasons.push("nft binary not found on this host — nat66 steps will fail honestly on exec");
  }

  const empty = steps.every((s) => s.kind === "dir") && !sysctlNeeded;
  const guarded = steps.every((s) => s.kind === "write" || ipv6StepGuarded(s.cmd));
  return {
    mode,
    steps,
    files,
    keaSubnets: kea.subnets,
    radvdIfaces: radvd.ifaces,
    nat66Statements: nat66.statements,
    skipped,
    reasons,
    warnings,
    refused: null,
    backupDir,
    preState: { keaRunning: facts.keaRunning, radvdRunning: facts.radvdRunning },
    keaStageFile: KEA6_STAGE_FILE,
    radvdStageFile: RADVD_STAGE_FILE,
    nat66File,
    keaChanged,
    radvdChanged,
    nat66Changed,
    sysctlNeeded,
    keaServiceWanted: keaWanted,
    radvdServiceWanted: radvdWanted,
    confHash: fnv1aHash(kea.text),
    radvdHash: fnv1aHash(radvd.text),
    nat66Hash: fnv1aHash(nat66.text),
    guarded,
    empty,
  };
}

// ── command guard (red lines — task whitelist, anchored) ────────────────────

/**
 * Allowlist for every executed IPv6 step (re-checked by the executor).
 * Exact matches for service/sysctl/probe commands; prefix-anchored with a
 * path check for validate/install/cleanup (staged files + state dir only).
 */
export function ipv6StepGuarded(cmd: string): boolean {
  const c = cmd.trim();
  if (!c) return false;
  if (c === "sysctl -w net.ipv6.conf.all.forwarding=1") return true;
  if (c === "sysctl -n net.ipv6.conf.all.forwarding") return true;
  if (c === `systemctl restart ${KEA6_SERVICE}`) return true;
  if (c === `systemctl stop ${KEA6_SERVICE}`) return true;
  if (c === `systemctl is-active ${KEA6_SERVICE}`) return true;
  if (c === `systemctl restart ${RADVD_SERVICE}`) return true;
  if (c === `systemctl stop ${RADVD_SERVICE}`) return true;
  if (c === `systemctl is-active ${RADVD_SERVICE}`) return true;
  if (c === "ss -ltn") return true;
  if (c === "ss -lun") return true;
  if (c === `mkdir -p ${IPV6_STATE_DIR}`) return true;
  if (c.startsWith("kea-dhcp6 -t ")) {
    const p = c.slice("kea-dhcp6 -t ".length).trim();
    return (
      p === KEA6_CONF_FILE ||
      p === KEA6_STAGE_FILE ||
      (p.startsWith(`${IPV6_STATE_DIR}/`) && !p.includes(".."))
    );
  }
  if (c.startsWith("radvd -c ")) {
    const p = c.slice("radvd -c ".length).trim();
    return p === RADVD_CONF_FILE || (p.startsWith(`${IPV6_STATE_DIR}/`) && !p.includes(".."));
  }
  if (c.startsWith("nft -c -f ") || c.startsWith("nft -f ")) {
    const p = c.replace(/^nft (-c )?-f /, "").trim();
    return (p.startsWith(`${IPV6_STATE_DIR}/`) || p === NAT66_ETC_FILE) && !p.includes("..");
  }
  if (c.startsWith("install -m 0644 ")) {
    const parts = c.slice("install -m 0644 ".length).trim().split(/\s+/);
    if (parts.length !== 2) return false;
    const [src, dst] = parts as [string, string];
    const srcOk =
      (src.startsWith(`${IPV6_STATE_DIR}/`) || src === KEA6_STAGE_FILE || src === "/dev/null") &&
      !src.includes("..");
    const dstOk =
      dst === KEA6_CONF_FILE ||
      dst === RADVD_CONF_FILE ||
      dst === NAT66_ETC_FILE ||
      (dst.startsWith(`${IPV6_STATE_DIR}/`) && !dst.includes(".."));
    return srcOk && dstOk;
  }
  if (c.startsWith(`cp ${KEA6_CONF_FILE} `)) {
    return c.slice(`cp ${KEA6_CONF_FILE} `.length).trim().startsWith(`${IPV6_STATE_DIR}/`);
  }
  if (c.startsWith(`cp ${RADVD_CONF_FILE} `)) {
    return c.slice(`cp ${RADVD_CONF_FILE} `.length).trim().startsWith(`${IPV6_STATE_DIR}/`);
  }
  if (c.startsWith(`rm -f ${IPV6_STATE_DIR}/`)) return !c.includes("..");
  if (c === `rm -f ${KEA6_STAGE_FILE}`) return true;
  return false;
}

// ── drift (GUI desired vs OS actual) ────────────────────────────────────────

export interface Ipv6DriftEntry {
  id: number;
  name: string;
  kind: "kea6" | "radvd" | "nat66" | "sysctl";
  osState: "in-sync" | "drift" | "missing" | "disabled" | "unsupported";
  detail: string | null;
}

export interface Ipv6RenderedSet {
  kea: { text: string; subnets: Kea6SubnetView[]; enabledServers: Dhcpv6ServerInput[] };
  radvd: { text: string; ifaces: RadvdIfaceView[] };
  nat66: { text: string; statements: Nat66Statement[] };
}

/**
 * Console intent vs OS reality. Hash-compare for kea6/radvd confs, normalized
 * block compare for the nat66 kernel table, value compare for sysctl, plus
 * per-server / per-iface / per-rule rows (in-sync | drift | missing |
 * disabled | unsupported).
 */
export function computeIpv6Drift(input: Ipv6OsInput, facts: Ipv6OsFacts, rendered: Ipv6RenderedSet): Ipv6DriftEntry[] {
  const entries: Ipv6DriftEntry[] = [];
  const serving = input.settings.enabled && input.settings.dhcpv6Enabled;

  // ── kea-dhcp6 section ──
  const keaInSync = facts.keaConfText !== null && fnv1aHash(facts.keaConfText) === fnv1aHash(rendered.kea.text);
  const keaWanted = keaServiceWanted(input);
  const keaServiceOk = keaWanted === "active" ? facts.keaRunning : !facts.keaRunning;

  if (!facts.keaAvailable) {
    entries.push({
      id: 0,
      name: "kea-dhcp6.conf",
      kind: "kea6",
      osState: "unsupported",
      detail: "kea-dhcp6 not installed on this host — DHCPv6 serving unavailable (config saved only)",
    });
  } else if (!facts.keaConfPresent) {
    entries.push({ id: 0, name: "kea-dhcp6.conf", kind: "kea6", osState: "missing", detail: "kea-dhcp6.conf not deployed — apply to OS" });
  } else {
    entries.push({
      id: 0,
      name: "kea-dhcp6.conf",
      kind: "kea6",
      osState: keaInSync && keaServiceOk ? "in-sync" : "drift",
      detail: keaInSync
        ? keaServiceOk
          ? `conf hash ${fnv1aHash(rendered.kea.text)} · service ${facts.keaRunning ? "active" : "inactive"} as wanted`
          : "conf matches, but kea-dhcp6-server state ≠ wanted (apply converges the service)"
        : "kea conf differs from GUI render — apply to OS",
    });
  }

  const liveIds = facts.keaConfText
    ? (() => {
        try {
          return liveKea6ManagedIds(parseKea6Conf(facts.keaConfText));
        } catch {
          return [];
        }
      })()
    : [];
  for (const s of input.servers) {
    const name = `${s.poolStart} → ${s.poolEnd} (${s.interfaceName})`;
    if (!s.enabled) {
      const stillThere = liveIds.includes(MANAGED_ID_BASE + s.id);
      entries.push({
        id: s.id,
        name,
        kind: "kea6",
        osState: stillThere ? "drift" : "disabled",
        detail: stillThere ? "disabled in GUI but still present in kea conf" : null,
      });
      continue;
    }
    if (!serving) {
      entries.push({ id: s.id, name, kind: "kea6", osState: "disabled", detail: "DHCPv6 disabled in IPv6 settings — server not rendered until enabled" });
      continue;
    }
    const deployed = liveIds.includes(MANAGED_ID_BASE + s.id);
    if (!deployed) {
      entries.push({ id: s.id, name, kind: "kea6", osState: "missing", detail: "enabled in GUI, not deployed as a managed subnet6 — apply to OS" });
      continue;
    }
    entries.push({
      id: s.id,
      name,
      kind: "kea6",
      osState: keaInSync ? "in-sync" : "drift",
      detail: keaInSync
        ? `kea id ${MANAGED_ID_BASE + s.id} · ${rendered.kea.subnets.find((k) => k.id === s.id)?.subnet ?? "?"}`
        : "kea conf differs from GUI render — apply to OS",
    });
  }

  // ── radvd section ──
  const radvdWanted = radvdServiceWanted(input);
  const radvdServiceOk = radvdWanted === "active" ? facts.radvdRunning : !facts.radvdRunning;
  const radvdInSync = facts.radvdConfText !== null && fnv1aHash(facts.radvdConfText) === fnv1aHash(rendered.radvd.text);
  if (!facts.radvdAvailable && radvdWanted === "active") {
    entries.push({ id: 0, name: "radvd.conf", kind: "radvd", osState: "unsupported", detail: "radvd not installed on this host — RA unavailable (config saved only)" });
  } else if (!facts.radvdConfPresent && radvdWanted === "active") {
    entries.push({ id: 0, name: "radvd.conf", kind: "radvd", osState: "missing", detail: "radvd.conf not deployed — apply to OS" });
  } else if (radvdWanted === "stopped") {
    entries.push({
      id: 0,
      name: "radvd.conf",
      kind: "radvd",
      osState: facts.radvdRunning ? "drift" : "in-sync",
      detail: facts.radvdRunning ? "RA disabled in console but radvd still running — stop on apply" : "RA disabled — radvd stopped",
    });
  } else {
    entries.push({
      id: 0,
      name: "radvd.conf",
      kind: "radvd",
      osState: radvdInSync && radvdServiceOk ? "in-sync" : "drift",
      detail: radvdInSync
        ? radvdServiceOk
          ? `RA ${input.settings.raMode} on ${rendered.radvd.ifaces.length} iface(s)`
          : "conf matches, but radvd state ≠ wanted"
        : "radvd.conf differs from GUI render — apply to OS",
    });
  }
  for (const ifaceView of rendered.radvd.ifaces) {
    entries.push({
      id: 0,
      name: `${ifaceView.iface} ${ifaceView.prefix}`,
      kind: "radvd",
      osState: facts.radvdAvailable ? (radvdInSync && facts.radvdConfPresent ? "in-sync" : facts.radvdConfPresent ? "drift" : "missing") : "unsupported",
      detail: `mode ${ifaceView.mode}`,
    });
  }

  // ── NAT66 section ──
  const tablePresent = facts.liveRuleset != null && new RegExp(`table ${NAT66_TABLE}\\b`).test(facts.liveRuleset);
  const nat66InSync = facts.liveRuleset != null && nat66BlocksInSync(rendered.nat66.text, facts.liveRuleset);
  if (!facts.nftAvailable && rendered.nat66.statements.length > 0) {
    entries.push({ id: 0, name: NAT66_TABLE, kind: "nat66", osState: "unsupported", detail: "nft not installed on this host — NAT66 unavailable (config saved only)" });
  } else if (!tablePresent && rendered.nat66.statements.length > 0) {
    entries.push({ id: 0, name: NAT66_TABLE, kind: "nat66", osState: "missing", detail: "utm_nat66 table absent from the kernel — apply to OS" });
  } else if (rendered.nat66.statements.length === 0 && !tablePresent) {
    entries.push({ id: 0, name: NAT66_TABLE, kind: "nat66", osState: "in-sync", detail: "no enabled NAT66 rules — table not rendered" });
  } else {
    entries.push({
      id: 0,
      name: NAT66_TABLE,
      kind: "nat66",
      osState: nat66InSync ? "in-sync" : "drift",
      detail: nat66InSync ? `${rendered.nat66.statements.length} statement(s) in the kernel table` : "utm_nat66 table differs from GUI render — apply to OS",
    });
  }
  const liveRuleIds = facts.liveRuleset ? [...facts.liveRuleset.matchAll(/nat66:(\d+):/g)].map((m) => Number(m[1])) : [];
  for (const r of input.nat66) {
    if (!r.enabled) {
      const stillThere = liveRuleIds.includes(r.id);
      entries.push({
        id: r.id,
        name: r.name,
        kind: "nat66",
        osState: stillThere ? "drift" : "disabled",
        detail: stillThere ? "disabled in GUI but still loaded in the kernel table" : null,
      });
      continue;
    }
    if (!liveRuleIds.includes(r.id)) {
      entries.push({ id: r.id, name: r.name, kind: "nat66", osState: "missing", detail: "enabled in GUI, not loaded in utm_nat66 — apply to OS" });
      continue;
    }
    entries.push({ id: r.id, name: r.name, kind: "nat66", osState: nat66InSync ? "in-sync" : "drift", detail: `${r.type} on ${r.interfaceName}` });
  }

  // ── sysctl forwarding ──
  const wantForward = sysctlNeededFor(input);
  entries.push({
    id: 0,
    name: "net.ipv6.conf.all.forwarding",
    kind: "sysctl",
    osState: !wantForward ? "in-sync" : facts.sysctlForwarding === true ? "in-sync" : facts.sysctlForwarding === false ? "drift" : "unsupported",
    detail:
      !wantForward
        ? "IPv6 serving disabled — forwarding not forced"
        : facts.sysctlForwarding === true
          ? "forwarding enabled"
          : facts.sysctlForwarding === false
            ? "forwarding OFF — apply sets it to 1"
            : "sysctl value unreadable on this host",
  });

  return entries;
}
