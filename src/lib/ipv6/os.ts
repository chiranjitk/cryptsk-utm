// ── deterministic hashing (local — keeps this module pure) ──────────────────

/** FNV-1a 32-bit — same algorithm as dhcp/os.ts; hash-stable per render. */
export function fnv1aHash(s: string): string {
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0).toString(16).padStart(8, "0");
}

