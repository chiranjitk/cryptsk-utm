/**
 * IPv6 OS layer (IMPL-6, spec 2.7) — the PURE core that bridges the console
 * IPv6 config to the real Debian 13 appliance (kea-dhcp6 2.6.3 + radvd +
 * nftables). Mirrors lib/waf/os.ts (pure renderer + plan) and the dhcp/os.ts
 * drift patterns. All fs/exec/db work lives in os-service.ts.
 *
 *   • renderKea6Conf        deterministic /etc/kea/kea-dhcp6.conf (full-file,
 *                           keepalived-style — it is the ONLY kea6 conf)
 *   • parseKea6Conf         JSON.parse with Kea `#` comment support
 *   • renderRadvdConf       /etc/radvd.conf from raMode (4-mode matrix + RDNSS)
 *   • renderNat66Nft        dedicated `inet utm_nat66` table file (atomic
 *                           destroy + recreate — never flushes the ruleset)
 *   • validateIpv6Inputs    cross-field refusals BEFORE any file write
 *   • buildIpv6ApplyPlan    snapshot → stage → validate → install → service →
 *                           sysctl → verify; state.json is written LAST by the
 *                           executor; failure restores all backups
 *   • ipv6StepGuarded       EXACT/anchored whitelist — no other exec path
 *   • computeIpv6Drift      console intent vs OS reality (hash + block compare)
 *
 * SAFETY CONTRACT (enforced in code):
 *   • kea conf renders at mode 0644 (kea runs as `_kea` on Debian — 0640 made
 *     the daemon fail to read its conf while root's `kea-dhcp6 -t` passed;
 *     same fix history as kea-dhcp4);
 *   • `kea-dhcp6 -t` / `radvd -c` / `nft -c -f` must pass on the STAGED file
 *     BEFORE the live conf is touched (validate-first);
 *   • `nft -f` files never contain `flush ruleset` — only the dedicated
 *     `inet utm_nat66` table is destroyed/recreated;
 *   • when dhcpv6 is disabled or no server is enabled the plan STOPS
 *     kea-dhcp6-server and renders a minimal valid empty config (honest);
 *   • when raMode is disabled the plan stops radvd (empty conf, no -c
 *     validation — radvd rejects a config without interface stanzas);
 *   • sysctl forwarding is only forced when IPv6 serving is actually wanted;
 *   • execution lives in os-service.ts and only runs when CONSOLE_OS_APPLY=1
 *     and the data plane is "host" — plan preview is always available.
 */

