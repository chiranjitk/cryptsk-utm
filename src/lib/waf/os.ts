/**
 * WAF OS layer (M17 §2.4 / spec §1.x) — the pure core that bridges the console
 * WAF config to the real nginx + ModSecurity 3 + OWASP CRS appliance:
 *
 *   • renderModsecSetup    deterministic per-vhost ModSecurity setup (tx vars)
 *   • renderModsecVhost    per-vhost ruleset (engine mode, CRS includes, exclusions)
 *   • renderWafManaged     the full managed real estate (conf.d + utm-waf/ + ssl/)
 *   • buildWafApplyPlan    step list (backup → write → nginx -t → start/reload → verify)
 *   • wafStepGuarded       EXACT-command whitelist — no other exec path
 *   • computeWafDrift      console intent vs OS reality (hash + unit only)
 *   • wafConfHash          sha256[:16] over concatenated managed files
 *
 * MANAGED REAL ESTATE (full-file-per-domain, keepalived-style):
 *   /etc/nginx/conf.d/utm-waf.conf   — limit_req zones + geo maps + server blocks
 *   /etc/nginx/utm-waf/<id>.conf     — ModSecurity ruleset per vhost
 *   /etc/nginx/utm-waf/<id>-setup.conf — SecAction id:900000 tx vars per vhost
 *   /etc/nginx/ssl/utm-<id>.crt/.key — TLS material staged from the PKI DB (PEM)
 *
 * SAFETY CONTRACT (enforced in code):
 *   • main nginx.conf is NEVER touched — only conf.d/utm-waf.conf + /etc/nginx/utm-waf/;
 *   • `nginx -t` must pass AFTER the files are staged and BEFORE reload (validate-after-stage);
 *   • previous files are backed up to WAF_STATE_DIR/backup-<ts>/ and restored
 *     automatically when validate/reload fails;
 *   • no enabled vhost → empty managed conf and the nginx unit is left alone
 *     (no start/reload steps at all);
 *   • execution lives in os-service.ts and only runs when CONSOLE_OS_APPLY=1
 *     and the data plane is "host" — plan preview is always available.
 */

