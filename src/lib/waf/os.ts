export function certPathsFor(vhostId: number): { cert: string; key: string } {
  return {
    cert: path.join(WAF_SSL_DIR, `utm-${vhostId}.crt`),
    key: path.join(WAF_SSL_DIR, `utm-${vhostId}.key`),
  };
}

/** One server { … } block + per-vhost modsec files (tests assert per-vhost output). */
export function renderVhostServerBlock(
  vhost: WafVhostInput,
  policy: WafPolicyInput | null,
  cert: WafCertInput | null,
  crsDir: string = CRS_BASE_DIR,
  exclusions: WafExclusionInput[] = [],
): RenderedVhost {
  const warnings: string[] = [];
  const id = vhost.id;
  const hostname = safeToken(vhost.hostname);
  const backendHost = safeToken(vhost.backendHost);
  const geoVar = `utm_geo_${id}`;
  const zoneName = `utm_waf_${id}`;

  const effectivePolicy =
    vhost.mode === "waf" && policy && policy.enabled && policy.vhostId === vhost.id ? policy : null;

  // TLS material resolution
  const useSsl = vhost.tls && !!vhost.certId && !!cert;
  const pkiFiles: WafFilePlan[] = [];
  if (vhost.tls && vhost.certId && cert) {
    const p = certPathsFor(id);
    pkiFiles.push({ path: p.cert, content: cert.certPem, backup: true, kind: "pki", vhostId: id });
    pkiFiles.push({ path: p.key, content: cert.keyPem, backup: true, kind: "pki", vhostId: id });
  } else if (vhost.tls && vhost.certId && !cert) {
    warnings.push(
      `vhost ${hostname}: TLS enabled but certificate ${vhost.certId} material is missing/inactive — listener rendered as plaintext :${vhost.listenPort}`,
    );
  }

  const modsec = effectivePolicy
    ? renderModsecVhost(vhost, effectivePolicy, exclusions, crsDir)
    : null;
  if (modsec) warnings.push(...modsec.warnings);
  const block = renderServerBlockLines(vhost, policy, effectivePolicy, cert, useSsl, warnings);

  let renderHashInput = block.join("\n");
  if (modsec) renderHashInput += `\n${modsec.conf}\n${modsec.setup}`;
  for (const f of pkiFiles) renderHashInput += `\n${f.path}:${wafHash(f.content)}`;

  return {
    id,
    hostname,
    mode: vhost.mode,
    serverBlock: block.join("\n") + "\n",
    modsec,
    pkiFiles,
    warnings,
    renderHash: wafHash(renderHashInput),
    policySummary: effectivePolicy
      ? {
          crs: effectivePolicy.owaspCrsEnabled,
          crsVersion: effectivePolicy.crsVersion,
          paranoiaLevel: effectivePolicy.paranoiaLevel,
          thresholds: { in: effectivePolicy.anomalyInThreshold, out: effectivePolicy.anomalyOutThreshold },
          learning: effectivePolicy.learningMode,
          rateLimit:
            effectivePolicy.rateLimitRpm != null
              ? { rpm: effectivePolicy.rateLimitRpm, burst: burstForPolicy(effectivePolicy) ?? 0 }
              : null,
        }
      : null,
  };
}

function renderServerBlockLines(
  vhost: WafVhostInput,
  policy: WafPolicyInput | null,
  activePolicy: WafPolicyInput | null,
  cert: WafCertInput | null,
  useSsl: boolean,
  warnings: string[],
): string[] {
  const L: string[] = [];
  const id = vhost.id;
  const hostname = safeToken(vhost.hostname);
  const backendHost = safeToken(vhost.backendHost);
  const geoVar = `utm_geo_${id}`;
  const zoneName = `utm_waf_${id}`;
  const geoActive = activePolicy != null && activePolicy.geoBlockCountries.length > 0;
  const burst = activePolicy ? burstForPolicy(activePolicy) : null;

  L.push(`# ── vhost ${id}: ${hostname} (${vhost.mode}${policy ? `, policy "${safeToken(policy.name, "policy")}"` : ", no policy"}) ──`);
  L.push("server {");
  L.push(`\tlisten ${vhost.listenPort}${useSsl ? " ssl" : ""};`);
  if (vhost.tls && useSsl) {
    const p = certPathsFor(id);
    L.push(`\tssl_certificate ${p.cert};`);
    L.push(`\tssl_certificate_key ${p.key};`);
    L.push("\tssl_protocols TLSv1.2 TLSv1.3;");
  } else if (vhost.tls && vhost.certId && !cert) {
    L.push(`\t# TLS requested but no usable certificate (see status warnings) — plaintext listener`);
  }
  L.push(`\tserver_name ${hostname};`);
  if (geoActive) {
    L.push(`\tif (\$${geoVar}) { return 403; }`);
  }
  if (burst != null) {
    L.push(`\tlimit_req zone=${zoneName} burst=${burst} nodelay;`);
  }
  L.push("\tlocation / {");
  if (activePolicy) {
    L.push("\t\tmodsecurity on;");
    L.push(`\t\tmodsecurity_rules_file ${path.join(WAF_RULES_DIR, `${id}.conf`)};`);
  } else if (vhost.mode === "waf" && policy && !policy.enabled) {
    L.push("\t\t# policy disabled in console — plain reverse proxy");
    warnings.push(`vhost ${hostname}: policy "${policy.name}" is disabled — rendered as plain reverse proxy`);
  } else if (vhost.mode === "waf") {
    L.push("\t\t# no policy attached — plain reverse proxy (attach a policy to enable ModSecurity)");
    warnings.push(`vhost ${hostname}: mode=waf but no policy attached — rendered as plain reverse proxy`);
  }
  L.push("\t\tproxy_set_header Host $host;");
  L.push("\t\tproxy_set_header X-Real-IP $remote_addr;");
  L.push("\t\tproxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;");
  L.push(`\t\tproxy_pass http://${backendHost}:${vhost.backendPort};`);
  L.push("\t}");
  L.push("}");
  return L;
}

export interface RenderWafResult {
  /** /etc/nginx/conf.d/utm-waf.conf text */
  mainConf: string;
  files: WafFilePlan[];
  /** per enabled vhost: server block + modsec files + summary */
  vhosts: RenderedVhost[];
  /** hostnames intentionally NOT rendered (disabled in console) */
  skipped: Array<{ hostname: string; reason: string }>;
  warnings: string[];
  managedVhostIds: number[];
  confHash: string;
  /** true when there is nothing to enforce (empty managed conf) */
  empty: boolean;
}

/**
 * Full render: main conf.d file + per-vhost modsec/setup files + PEM staging.
 * Deterministic — identical inputs → byte-identical files (hash-stable).
 */
export function renderWafManaged(
  inputs: WafInputs,
  opts: { crsDir?: string } = {},
): RenderWafResult {
  const crsDir = opts.crsDir ?? CRS_BASE_DIR;
  const warnings: string[] = [];
  const skipped: RenderWafResult["skipped"] = [];
  const policyByVhost = new Map<number, WafPolicyInput>();
  for (const p of inputs.policies) {
    // one policy per vhost is enforced at the API layer; last-write wins here
    if (!policyByVhost.has(p.vhostId)) policyByVhost.set(p.vhostId, p);
  }
  const exclusionsByPolicy = new Map<number, WafExclusionInput[]>();
  for (const x of inputs.exclusions) {
    const list = exclusionsByPolicy.get(x.policyId) ?? [];
    list.push(x);
    exclusionsByPolicy.set(x.policyId, list);
  }
  const certById = new Map<number, WafCertInput>();
  for (const c of inputs.certs) certById.set(c.certId, c);

  const zoneLines: string[] = [];
  const geoLines: string[] = [];
  const serverLines: string[] = [];
  const files: WafFilePlan[] = [];
  const renderedVhosts: RenderedVhost[] = [];
  const managedVhostIds: number[] = [];

  for (const v of inputs.vhosts) {
    if (!v.enabled) {
      skipped.push({ hostname: v.hostname, reason: "vhost disabled in console" });
      continue;
    }
    const policy = policyByVhost.get(v.id) ?? null;
    const cert = v.certId != null ? (certById.get(v.certId) ?? null) : null;
    const xs = policy ? (exclusionsByPolicy.get(policy.id) ?? []) : [];
    const rendered = renderVhostServerBlock(v, policy, cert, crsDir, xs);

    // modsec files are materialized when the vhost actually inspects traffic
    const modsec = policy && v.mode === "waf" && policy.enabled ? rendered.modsec : null;
    if (modsec) {
      files.push({ path: path.join(WAF_RULES_DIR, `${v.id}.conf`), content: modsec.conf, backup: true, kind: "modsec", vhostId: v.id });
      files.push({ path: path.join(WAF_RULES_DIR, `${v.id}-setup.conf`), content: modsec.setup, backup: true, kind: "modsec", vhostId: v.id });
    }

    // rate-limit zone + geo map (policy-driven; disabled policies contribute nothing)
    if (policy && policy.enabled && policy.rateLimitRpm != null) {
      zoneLines.push(
        `limit_req_zone $binary_remote_addr zone=utm_waf_${v.id}:10m rate=${Math.ceil(policy.rateLimitRpm / 60)}r/s; # ${policy.rateLimitRpm} rpm ≈ ${rpmToRps(policy.rateLimitRpm)} r/s`,
      );
    }
    const geoCcs = (policy?.geoBlockCountries ?? [])
      .map(safeCountryCode)
      .filter((cc): cc is string => cc !== null);
    if (policy && policy.enabled && geoCcs.length > 0) {
      const body = ["default 0;", ...geoCcs.map((cc) => `${cc} 1;`)].map((l) => `\t${l}`);
      geoLines.push(`geo $utm_geo_${v.id} {`, ...body, "}");
    }

    serverLines.push(rendered.serverBlock.trimEnd());
    files.push(...rendered.pkiFiles);
    warnings.push(...rendered.warnings);
    renderedVhosts.push({ ...rendered, modsec });
    managedVhostIds.push(v.id);
  }

  // ── main managed file ──
  const L: string[] = [];
  L.push(MANAGED_HEADER);
  L.push(`# /etc/nginx/conf.d/${WAF_MANAGED_NAME} — nginx + ModSecurity 3 vhosts`);
  L.push(`# main nginx.conf is NOT console-owned; only this file and ${WAF_RULES_DIR}/ are.`);
  L.push(`# vhosts rendered: ${managedVhostIds.length} · applied via nginx -t → systemctl reload nginx`);
  L.push("");
  if (zoneLines.length > 0) {
    L.push("# ── rate-limit zones (rate=⌈rpm/60⌉ r/s per policy) ──");
    for (const z of zoneLines) L.push(z);
    L.push("");
  }
  if (geoLines.length > 0) {
    L.push("# ── geo maps (country block → 403) ──");
    for (const g of geoLines) L.push(g);
    L.push("");
  }
  if (serverLines.length > 0) {
    for (const s of serverLines) {
      L.push(s);
      L.push("");
    }
  } else {
    L.push("# No ENABLED vhosts — console renders an empty managed conf and does NOT");
    L.push("# start/reload nginx (the unit state is reported as-is in the status API).");
    L.push("");
  }
  if (skipped.length > 0) {
    for (const s of skipped) L.push(`# skipped: ${s.hostname} (${s.reason})`);
    L.push("");
  }
  L.push(MANAGED_FOOTER);
  const mainConf = L.join("\n") + "\n";

  const allFiles: WafFilePlan[] = [
    { path: WAF_MANAGED_FILE, content: mainConf, backup: true, kind: "nginx", vhostId: 0 },
    ...files,
  ];
  const empty = managedVhostIds.length === 0;
  return {
    mainConf,
    files: allFiles,
    vhosts: renderedVhosts,
    skipped,
    warnings,
    managedVhostIds,
    confHash: wafConfHash(allFiles.map((f) => ({ path: f.path, content: f.content }))),
    empty,
  };
}

// ── apply plan ──────────────────────────────────────────────────────────────

export type WafStepKind = "dir" | "backup" | "write" | "cleanup" | "validate" | "reload" | "verify" | "probe";

export interface WafPlanStep {
  step: string;
  cmd: string;
  kind: WafStepKind;
  /** probes / best-effort cleanup — failure recorded, no rollback */
  optional?: boolean;
}

export interface WafApplyPlan {
  mode: "exec" | "plan";
  files: WafFilePlan[];
  steps: WafPlanStep[];
  backupDir: string;
  confHash: string;
  warnings: string[];
  /** per-vhost preview (hostname, mode, renderHash, policy summary, warnings) */
  vhosts: RenderedVhost[];
  managedVhostIds: number[];
  empty: boolean;
  guarded: boolean;
  refused: string | null;
}

/**
 * Validate-after-stage apply plan:
 *   1. state/rules dirs
 *   2. backup live managed files → WAF_STATE_DIR/backup-<ts>/
 *   3. stage all managed files (conf.d + modsec + setup + PEM) via fs writes
 *   4. clean up stale per-vhost files (rm -f …, rmdir when empty)
 *   5. `nginx -t` — validates the LIVE tree (Debian default nginx.conf is valid);
 *      failure → backups restored + revalidated by the executor
 *   6. activate: systemctl start nginx (unit inactive) or reload (active)
 *   7. verify: is-active + `nginx -t` again + listener probe (informational)
 *
 * NO vhosts → empty managed conf, cleanup only, NO activate/verify steps.
 */
export function buildWafApplyPlan(
  inputs: WafInputs,
  facts: Pick<WafOsFacts, "unitState" | "managedFiles"> & { available?: boolean },
  mode: "exec" | "plan",
  ts: string,
  opts: { crsDir?: string } = {},
): WafApplyPlan {
  const rendered = renderWafManaged(inputs, opts);
  const backupDir = `${WAF_STATE_DIR}/backup-${ts}`;
  const steps: WafPlanStep[] = [];

  steps.push({ step: "state dir", cmd: `mkdir -p ${WAF_STATE_DIR}`, kind: "dir" });
  if (!rendered.empty) {
    steps.push({ step: "rules dir", cmd: `mkdir -p ${WAF_RULES_DIR}`, kind: "dir" });
  }

  // backups of currently-present managed files (cp is guarded; executor skips
  // steps whose source vanished since planning)
  const presentOnDisk = new Set(facts.managedFiles.filter((f) => f.present).map((f) => f.path));
  for (const f of rendered.files) {
    if (presentOnDisk.has(f.path)) {
      steps.push({ step: `backup ${path.basename(f.path)}`, cmd: `cp ${f.path} ${backupDir}/${f.path}`, kind: "backup" });
    }
  }

  // stage files
  for (const f of rendered.files) {
    steps.push({ step: `write ${path.basename(f.path)}`, cmd: `write-file ${f.path}`, kind: "write" });
  }

  // stale per-vhost cleanup: on-disk utm-*.conf files no longer managed
  const managedPaths = new Set(rendered.files.map((f) => f.path));
  for (const f of facts.managedFiles) {
    if (f.path.startsWith(`${WAF_RULES_DIR}/`) && f.present && !managedPaths.has(f.path)) {
      steps.push({ step: `cleanup ${path.basename(f.path)}`, cmd: `rm -f ${f.path}`, kind: "cleanup" });
    }
  }
  if (rendered.empty) {
    steps.push({ step: "cleanup rules dir", cmd: `rmdir ${WAF_RULES_DIR}`, kind: "cleanup", optional: true });
  }

  // validate AFTER staging, BEFORE reload
  steps.push({ step: "validate config", cmd: "nginx -t", kind: "validate" });

  if (!rendered.empty) {
    const startNeeded = facts.unitState !== "active";
    steps.push({
      step: startNeeded ? "start nginx" : "reload nginx",
      cmd: startNeeded ? "systemctl start nginx" : "systemctl reload nginx",
      kind: "reload",
    });
    steps.push({ step: "verify unit", cmd: "systemctl is-active nginx", kind: "verify" });
    steps.push({ step: "re-verify config", cmd: "nginx -t", kind: "verify" });
    steps.push({
      step: "probe listeners",
      cmd: "ss -ltn '( sport = :443 or sport = :80 )'",
      kind: "probe",
      optional: true,
    });
  }

  const refused = hardWafRefusal(inputs);
  return {
    mode,
    files: rendered.files,
    steps,
    backupDir,
    confHash: rendered.confHash,
    warnings: rendered.warnings,
    vhosts: rendered.vhosts,
    managedVhostIds: rendered.managedVhostIds,
    empty: rendered.empty,
    guarded: steps.every((s) => wafStepGuarded(s.cmd)),
    refused,
  };
}

/** Hard red-line refusals — checked before any exec. */
export function hardWafRefusal(inputs: WafInputs): string | null {
  for (const v of inputs.vhosts) {
    if (!v.enabled) continue;
    const bad = [v.hostname, v.backendHost].some((h) => /["'\\\s;$`]/.test(h));
    if (bad) {
      return `refused: vhost ${v.id} has characters in hostname/backendHost that nginx cannot carry safely — fix the vhost first`;
    }
  }
  for (const p of inputs.policies) {
    if (p.rateLimitRpm != null && (p.rateLimitRpm < 10 || p.rateLimitRpm > 10000)) {
      return `refused: policy "${p.name}" rateLimitRpm ${p.rateLimitRpm} outside 10–10000 (validator bypass?)`;
    }
  }
  return null;
}

// ── command whitelist (haStepGuarded pattern) ───────────────────────────────

function isUnderRulesDir(p: string): boolean {
  return p.startsWith(`${WAF_RULES_DIR}/`) && !p.includes("..") && p.length > WAF_RULES_DIR.length + 1;
}

function isStageablePath(p: string): boolean {
  if (p === WAF_MANAGED_FILE) return true;
  if (isUnderRulesDir(p)) return true;
  // TLS material: /etc/nginx/ssl/utm-<vhostId>.crt|.key only
  return new RegExp(`^${WAF_SSL_DIR.replace(/\//g, "\\/")}/utm-\\d+\\.(crt|key)$`).test(p) && !p.includes("..");
}

/** EXACT-command whitelist for WAF apply — nothing else may execute. */
export function wafStepGuarded(cmd: string): boolean {
  const c = cmd.trim();
  if (!c) return false;
  if (c === "nginx -t") return true;
  if (c === "systemctl start nginx") return true;
  if (c === "systemctl reload nginx") return true;
  if (c === "systemctl is-active nginx") return true;
  if (c === "ss -ltn '( sport = :443 or sport = :80 )'") return true;
  if (c === `mkdir -p ${WAF_STATE_DIR}`) return true;
  if (c === `mkdir -p ${WAF_RULES_DIR}`) return true;
  if (c === `mkdir -p ${WAF_SSL_DIR}`) return true;
  if (c === `rmdir ${WAF_RULES_DIR}`) return true;
  if (c === `rm -f ${WAF_MANAGED_FILE}`) return true; // rollback path only
  // backup cp: /etc/nginx/... → WAF_STATE_DIR/backup-<ts>/<same abs path>
  const cpBackup = /^cp (\S+) (\S+)$/.exec(c);
  if (cpBackup) {
    const [, src, dst] = cpBackup;
    if (
      (src === WAF_MANAGED_FILE || isUnderRulesDir(src) || isStageablePath(src)) &&
      dst.startsWith(`${WAF_STATE_DIR}/backup-`) &&
      !dst.includes("..")
    ) {
      return true;
    }
  }
  // staged writes are flagged in the plan ("write-file <path>") — the executor
  // performs them via node fs (ha/dhcp pattern); the cmd is whitelisted so a
  // plan preview can display them without lying about how they run.
  const wf = /^write-file (\S+)$/.exec(c);
  if (wf && isStageablePath(wf[1])) return true;
  // stale cleanup
  const rm = /^rm -f (\S+)$/.exec(c);
  if (rm && isUnderRulesDir(rm[1])) return true;
  return false;
}

/** Runtime check: backup dirs live in WAF_STATE_DIR and match backup-<ts>. */
export function isWafBackupDir(dir: string): boolean {
  if (!dir.startsWith(`${WAF_STATE_DIR}/`)) return false;
  if (dir.includes("..")) return false;
  return WAF_BACKUP_RE.test(dir.split("/").pop() ?? "");
}

// ── drift (console intent vs OS reality) ────────────────────────────────────

export interface WafDrift {
  inSync: boolean;
  managedByConsole: boolean;
  reasons: string[];
}

/**
 * inSync flips ONLY on (a) file hash vs last applied state and (b) unit state.
 * `renderedHash` (current console intent) must match too — a policy edit after
 * the last apply IS drift until the operator applies again.
 */
export function computeWafDrift(
  facts: Pick<WafOsFacts, "available" | "unitState" | "confHash" | "stateHash">,
  renderedHash: string,
  enabledVhostCount: number,
): WafDrift {
  const reasons: string[] = [];
  const managedByConsole = Boolean(facts.stateHash && facts.confHash && facts.stateHash === facts.confHash);

  if (!facts.available) {
    return { inSync: false, managedByConsole, reasons: ["nginx/ModSecurity not available on this host"] };
  }
  if (facts.confHash == null) {
    reasons.push("managed files not deployed — apply to OS");
  } else if (!managedByConsole) {
    reasons.push("managed files changed outside the console (hash ≠ last applied)");
  } else if (facts.stateHash !== renderedHash) {
    reasons.push("console config changed since last apply — apply to OS");
  }
  if (enabledVhostCount > 0 && facts.unitState !== "active") {
    reasons.push(`nginx service is ${facts.unitState ?? "unknown"}, expected active`);
  }

  return { inSync: reasons.length === 0, managedByConsole, reasons };
}

// ── nginx -t interpretation (mirror of interpretKeepalivedTest) ─────────────

export interface NginxTestResult {
  ok: boolean;
  hasErrors: boolean;
  warnings: string[];
  detail: string;
}

/**
 * `nginx -t` writes "syntax is ok / test is successful" on stderr with rc=0;
 * anything else is a hard failure (nginx has no warning-only exit).
 */
export function interpretNginxTest(output: string, execOk: boolean): NginxTestResult {
  const lines = output.split("\n").map((l) => l.trim()).filter(Boolean);
  const errorLines = lines.filter((l) => /\b(emerg|error|failed)\b/i.test(l) && !/is ok|successful/i.test(l));
  const okLines = lines.filter((l) => /syntax is ok|test is successful/i.test(l));
  const warnings = lines.filter((l) => /\bwarn\b/i.test(l));
  const hasErrors = errorLines.length > 0 || (!execOk && okLines.length === 0);
  return {
    ok: !hasErrors,
    hasErrors,
    warnings,
    detail: hasErrors
      ? errorLines.join(" | ").slice(0, 400) || "nginx -t failed (exec error)"
      : warnings.length > 0
        ? `nginx -t passed with ${warnings.length} warning(s): ${warnings.join(" | ").slice(0, 300)}`
        : execOk
          ? "nginx -t passed (syntax ok)"
          : "nginx -t failed with no output (exec error)",
  };
}
