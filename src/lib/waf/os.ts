// ── deterministic hashing ───────────────────────────────────────────────────

/** Per-file / per-vhost hash — sha256, first 16 hex chars. */
export function wafHash(text: string): string {
  return createHash("sha256").update(text).digest("hex").slice(0, 16);
}

/** confHash: sha256[:16] over the CONCATENATED managed files, sorted by path. */
export function wafConfHash(contents: Array<{ path: string; content: string }>): string {
  const sorted = [...contents].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  return createHash("sha256")
    .update(sorted.map((f) => f.content).join(""))
    .digest("hex")
    .slice(0, 16);
}

// ── sanitizers (defensive — API validation is the first line) ───────────────

function safeToken(v: string, fallback = "invalid"): string {
  const s = v.replace(/[^\w.-]/g, "").slice(0, 253);
  return s || fallback;
}

function safeCountryCode(cc: string): string | null {
  const s = cc.trim().toUpperCase();
  return /^[A-Z]{2}$/.test(s) ? s : null;
}

/** Strip characters that would break a quoted ModSecurity operator string. */
function safeUrlLiteral(v: string): string {
  return v.trim().replace(/["\\\n\r]/g, "").slice(0, 200);
}

// ── ModSecurity per-vhost rendering ─────────────────────────────────────────

/**
 * The per-vhost CRS setup file: our own crs-setup.conf replacement. Only the
 * tx vars the console manages (paranoia level + anomaly thresholds) — the
 * CRS bundle defaults carry the rest. id:900000 is outside every CRS rule id.
 */
export function renderModsecSetup(policy: WafPolicyInput): string {
  const L: string[] = [];
  L.push(`# UTM console managed — ModSecurity setup for policy "${safeToken(policy.name, "policy")}"`);
  L.push(`# tx vars only — the CRS bundle (rules/*.conf) consumes them at runtime.`);
  L.push('SecAction "\\');
  L.push(`  id:900000,\\`);
  L.push(`  phase:1,\\`);
  L.push(`  pass,\\`);
  L.push(`  nolog,\\`);
  L.push(`  t:none,\\`);
  L.push(`  setvar:tx.paranoia_level=${policy.paranoiaLevel},\\`);
  L.push(`  setvar:tx.executing_paranoia_level=${policy.paranoiaLevel},\\`);
  L.push(`  setvar:tx.inbound_anomaly_score_threshold=${policy.anomalyInThreshold},\\`);
  L.push(`  setvar:tx.outbound_anomaly_score_threshold=${policy.anomalyOutThreshold},\\`);
  // CRS 901001 (REQUEST-901-INITIALIZATION) hard-fails (500) when
  // tx.crs_setup_version is unset — "CRS deployed without configuration".
  // 333 = CRS 3.3.x series (the version the appliance ships: 3.3.7).
  L.push(`  setvar:tx.crs_setup_version=333\\"`);
  L.push("SecRequestBodyAccess On");
  L.push("SecResponseBodyAccess Off");
  return L.join("\n") + "\n";
}

export type ParamTarget = "ARGS" | "REQUEST_COOKIES" | "REQUEST_HEADERS";

/** matchValue "arg:password" → ARGS:password (cookie:/header: likewise). */
export function paramTargetFromMatchValue(matchValue: string): ParamTarget | null {
  const m = /^(arg|cookie|header):([\w.-]+)$/i.exec(matchValue.trim());
  if (!m) return null;
  const kind = m[1].toLowerCase();
  if (kind === "arg") return "ARGS";
  if (kind === "cookie") return "REQUEST_COOKIES";
  return "REQUEST_HEADERS";
}

export interface RenderedModsec {
  conf: string;
  setup: string;
  warnings: string[];
  crsIncluded: boolean;
}

/**
 * Per-vhost ModSecurity ruleset:
 *   SecRuleEngine  — learningMode → DetectionOnly (log-only), else On
 *   includes       — our setup file always; the CRS rules glob when enabled
 *   exclusions     — rule_id → SecRuleRemoveById, param → SecRuleUpdateTargetById,
 *                    url → ctl:ruleEngine=Off bypass rule (phase:1)
 */
export function renderModsecVhost(
  vhost: Pick<WafVhostInput, "id" | "hostname" | "mode">,
  policy: WafPolicyInput,
  exclusions: WafExclusionInput[],
  crsDir: string = CRS_BASE_DIR,
): RenderedModsec {
  const warnings: string[] = [];
  const L: string[] = [];
  L.push(`# UTM console managed — ModSecurity ruleset for vhost ${vhost.id} (${safeToken(vhost.hostname)})`);
  L.push(`# policy: ${safeToken(policy.name, "policy")} (db id ${policy.id})`);
  L.push(`SecRuleEngine ${policy.learningMode ? "DetectionOnly" : "On"}`);
  L.push("");

  L.push(`# console-managed tx setup (paranoia level, anomaly thresholds, body access)`);
  L.push(`Include ${path.join(WAF_RULES_DIR, `${vhost.id}-setup.conf`)}`);
  L.push("");

  let crsIncluded = false;
  if (policy.owaspCrsEnabled) {
    if (policy.crsVersion !== "3.3") {
      warnings.push(
        `policy "${policy.name}": CRS ${policy.crsVersion} requested but not installed — Debian package ${INSTALLED_CRS_VERSION} enforced`,
      );
    }
    L.push(`# OWASP CRS ${INSTALLED_CRS_VERSION} bundle (ModSecurity 3 parser supports Include globs)`);
    L.push(`Include ${crsDir}/rules/*.conf`);
    crsIncluded = true;
    L.push("");
  } else {
    L.push(`# OWASP CRS disabled for this policy — engine + tx setup only`);
    L.push("");
  }

  const active = exclusions.filter((x) => x.enabled);
  if (active.length > 0) {
    L.push(`# exclusions (${active.length}) — tuned false-positive relief`);
    let urlSeq = 0;
    for (const x of active) {
      if (x.scope === "rule_id") {
        const id = x.matchValue.trim();
        if (!/^\d{1,7}$/.test(id)) {
          warnings.push(`exclusion #${x.id}: rule_id matchValue "${x.matchValue}" is not a numeric CRS rule id — skipped`);
          continue;
        }
        L.push(`SecRuleRemoveById ${id}`);
      } else if (x.scope === "param") {
        if (x.ruleId == null) {
          warnings.push(
            `exclusion #${x.id}: param scope "${x.matchValue}" needs a target ruleId (SecRuleUpdateTargetById is rule-scoped) — skipped`,
          );
          continue;
        }
        const target = paramTargetFromMatchValue(x.matchValue);
        if (!target) {
          warnings.push(
            `exclusion #${x.id}: param matchValue "${x.matchValue}" must be "arg:<name>"/"cookie:<name>"/"header:<name>" — skipped`,
          );
          continue;
        }
        const name = safeToken(x.matchValue.split(":", 2)[1] ?? "", "unknown");
        L.push(`SecRuleUpdateTargetById ${x.ruleId} "!${target}:${name}"`);
      } else if (x.scope === "url") {
        const value = safeUrlLiteral(x.matchValue);
        if (!value) {
          warnings.push(`exclusion #${x.id}: url matchValue is empty after sanitization — skipped`);
          continue;
        }
        urlSeq += 1;
        // deterministic bypass id: 990000 + <vhostId> + <seq> — above the CRS
        // rule blocks we tune (910xxx–980xxx), unique within this vhost's
        // ruleset (vhost ids + small exclusion counts stay collision-free)
        const bypassId = String(990000 + vhost.id + urlSeq);
        L.push(`SecRule REQUEST_URI "@beginsWith ${value}" "id:${bypassId},phase:1,pass,nolog,ctl:ruleEngine=Off"`);
      } else {
        warnings.push(`exclusion #${x.id}: unknown scope "${x.scope}" — skipped`);
      }
    }
    L.push("");
  }

  const conf = L.join("\n") + "\n";
  return { conf, setup: renderModsecSetup(policy), warnings, crsIncluded };
}

// ── nginx server blocks + managed files ─────────────────────────────────────

/** r/s equivalent of the rpm knob (nginx zone rate is rendered as r/m). */
export function rpmToRps(rpm: number): number {
  return Math.round((rpm / 60) * 100) / 100;
}

/** limit_req burst: explicit knob, else the per-second equivalent (≥1). */
export function burstForPolicy(policy: Pick<WafPolicyInput, "rateLimitRpm" | "rateLimitBurst">): number | null {
  if (policy.rateLimitRpm == null) return null;
  if (policy.rateLimitBurst != null) return policy.rateLimitBurst;
  return Math.max(1, Math.round(policy.rateLimitRpm / 60));
}

