/**
 * SSL/TLS Inspection OS integration (M15 §2.1, GUI ↔ Squid ssl-bump) — PURE
 * core: deterministic conf.d fragment renderer, command whitelist, apply-plan
 * builder, drift computation and capability parsing. NO db / fs / exec imports
 * here — those live in os-service.ts (mirrors url-filter/os.ts + waf/os.ts).
 *
 * MANAGED REAL ESTATE — FRAGMENT, NOT THE MAIN CONF (hard constraint):
 *   /etc/squid/squid.conf is FULL-FILE owned by the URL-Filter module. This
 *   module NEVER touches it. The MITM flow ships as its own fragment:
 *     /etc/squid/conf.d/utm-ssl.conf   ssl_bump flow + sslproxy_* + sslcrtd
 *
 * HONEST LIMITATION surfaced as a mandatory warning (matches url-filter/os.ts
 * documentation): Debian's stock squid.conf ends its access section with
 * `http_access deny all` BEFORE the trailing `include /etc/squid/conf.d/*.conf`
 * (and the console-managed url-filter conf also keeps that include LAST), so
 * conf.d fragments are parsed AFTER the catch-all deny. http_access lines in a
 * fragment would be dead (first-match-wins); ssl_bump / sslproxy_cert_error /
 * sslcrtd_program are SEPARATE directive chains consulted after http_access
 * allows a CONNECT, so the fragment stays effective. The fragment therefore
 * never renders http_access — it rides on the URL-Filter module's access
 * policy and only decides splice/peek/bump.
 *
 * Rendering oracle: the simulated decision engine `runDecisionEngine()`
 * (api/v1/ssl-inspection/shared.ts) — bypass rules (insertion order) > policy
 * mode > pinning list > invalid-cert > HSTS > inspect. The fragment mirrors
 * that branch order with an ssl_bump chain (splice > terminate > peek > bump)
 * for the FIRST enabled policy (the engine also evaluates exactly one policy,
 * first enabled by id asc). Other enabled policies are reported as skipped,
 * never silently dropped.
 *
 * Capability honesty (spec §6 gap): Debian's stock squid is built WITHOUT
 * --enable-ssl-crtd, so dynamic cert generation cannot run. When capability
 * detection reports sslCrtdSupported=false and a MITM policy is enabled, the
 * apply plan is REFUSED with an actionable message (install/compile squid
 * with ssl-crtd, or use the cert-pinning-bypass-only mode). Never silently.
 */

