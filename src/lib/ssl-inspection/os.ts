// ── hashing ─────────────────────────────────────────────────────────────────

/** sha256[:16] — drift compares the LIVE fragment hash with the rendered hash. */
export function sha256_16(text: string): string {
  return createHash("sha256").update(text, "utf8").digest("hex").slice(0, 16);
}

// ── pure helpers ────────────────────────────────────────────────────────────

/** One-line comment-safe policy name (no newlines, bounded length). */
export function sanitizeComment(name: string, max = 64): string {
  const safe = name.replace(/[\r\n]+/g, " ").trim().slice(0, max);
  return safe || "unnamed";
}

const ACL_ID_RE = /^[a-z0-9_]+$/;

/** squid-name-safe deterministic ACL names (throws on impossible ids). */
export function sslAclName(kind: "dom" | "dst" | "pin" | "step", policyId: number): string {
  const name = `utm_ssl_${kind}_${policyId}`;
  if (!ACL_ID_RE.test(name)) throw new Error(`unsafe acl name: ${name}`);
  return name;
}

/**
 * Bypass-rule value → dstdomain token.
 *   domain    → `.value`   (leading dot covers subdomains)
 *   wildcard  → `.base`    (`*.base` is exactly dstdomain `.base`)
 * Null when the matchType is not a dstdomain kind.
 */
export function bypassToDstdomain(matchType: string, value: string): string | null {
  if (matchType !== "domain" && matchType !== "wildcard") return null;
  const v = value.trim();
  return v.startsWith("*.") ? `.${v.slice(2)}` : `.${v}`;
}

/** Bypass-rule value → dst ACL token (ip or cidr), null for other types. */
export function bypassToDst(matchType: string, value: string): string | null {
  if (matchType !== "ip" && matchType !== "cidr") return null;
  return value.trim();
}

/**
 * Capability parse: `squid -v` prints the full ./configure line — ssl-crtd
 * capable builds carry the `--enable-ssl-crtd` switch.
 */
export function sslCrtdFromVersionOutput(output: string): boolean {
  return /--enable-ssl-crtd\b/.test(output);
}

/**
 * `squid -k parse` verdict — rc=0 plus no FATAL line means the live tree
 * (squid.conf + conf.d fragments) parsed. Warn lines are reported, not fatal.
 */
export function interpretSquidParse(
  output: string,
  execOk: boolean,
): { ok: boolean; warnings: string[]; detail: string } {
  const lines = output.split("\n").map((l) => l.trim()).filter(Boolean);
  const fatal = lines.filter((l) => /\bFATAL\b/i.test(l) || /cannot find|unknown directive|unrecognized/i.test(l));
  const warnings = lines.filter((l) => /\bwarn(ing)?\b/i.test(l));
  const ok = execOk && fatal.length === 0;
  return {
    ok,
    warnings,
    detail: !execOk
      ? "squid -k parse failed (exec error)"
      : fatal.length > 0
        ? fatal.join(" | ").slice(0, 400)
        : warnings.length > 0
          ? `parsed OK with ${warnings.length} warning(s): ${warnings.join(" | ").slice(0, 300)}`
          : "squid -k parse passed (configuration tree OK)",
  };
}

// ── effective-policy selection (engine parity) ──────────────────────────────

/**
 * The simulated engine evaluates exactly ONE policy — the first ENABLED one
 * by id asc (runDecisionEngine). The fragment renders the first enabled
 * policy that actually requires MITM (mode selective|full); an enabled
 * mode=none policy means "no inspection" and yields an empty fragment.
 * Returns the chosen policy, whether MITM is required, and every other
 * enabled policy as a skipped entry (never silently dropped).
 */
export function effectivePolicy(inputs: SslRenderInput): {
  policy: SslPolicyInput | null;
  needsSslBump: boolean;
  skipped: Array<{ name: string; reason: string }>;
} {
  const skipped: Array<{ name: string; reason: string }> = [];
  const enabled = inputs.policies.filter((p) => p.enabled).sort((a, b) => a.id - b.id);
  const chosen = enabled.find((p) => p.mode === "selective" || p.mode === "full") ?? null;
  for (const p of enabled) {
    if (p === chosen) continue;
    skipped.push({
      name: `policy "${sanitizeComment(p.name)}" (db id ${p.id})`,
      reason:
        p.mode === "none"
          ? "mode none — no MITM; the first enabled selective/full policy owns the ssl_bump chain"
          : chosen
            ? `lower priority than policy id ${chosen.id} — squid ssl_bump chains are global (first-match-wins), only one policy renders`
            : "mode none — no MITM",
    });
  }
  return { policy: chosen, needsSslBump: chosen !== null, skipped };
}

// ── fragment renderer ───────────────────────────────────────────────────────

export interface SslRenderResult {
  /** /etc/squid/conf.d/utm-ssl.conf text */
  conf: string;
  /** sha256[:16] over conf — drift/state hash */
  confHash: string;
  warnings: string[];
  skipped: Array<{ name: string; reason: string }>;
  /** the policy that owns the rendered ssl_bump chain (null → empty fragment) */
  policy: SslPolicyInput | null;
  /** true when a selective/full policy is enabled (bump flow + listener + sslcrtd) */
  needsSslBump: boolean;
  /** rendered splice ACL names in order (bypass groups first, then pinning) */
  spliceAcls: string[];
}

/**
 * Render the conf.d fragment. Deterministic: identical inputs → byte-identical
 * output (hash-stable). Grouping: dstdomain bypass values and dst bypass
 * values each collapse into ONE ACL per policy (squid ACLs on a directive
 * line are AND-combined, so OR-groups get their own acl + splice line).
 */
export function renderSslFragment(inputs: SslRenderInput): SslRenderResult {
  const warnings: string[] = [];
  const { policy, needsSslBump, skipped } = effectivePolicy(inputs);

  // (a) mandatory include-order honesty note — ALWAYS surfaced
  warnings.push(
    `conf.d include order: ${SQUID_MAIN_CONF} access rules (stock "http_access deny all", and the ` +
      `console-managed URL-Filter conf) are parsed BEFORE ${SQUID_CONF_D_INCLUDE} — http_access lines in ` +
      `this fragment would be dead; ssl_bump/sslproxy_cert_error/sslcrtd_program are separate chains and stay effective. ` +
      `The fragment therefore renders no http_access and never touches ${SQUID_MAIN_CONF} (URL-Filter module owns it).`,
  );

  const L: string[] = [MANAGED_HEADER];
  L.push(`# ${SSL_MANAGED_FILE} — squid ssl-bump fragment (M15 §2.1, MITM inspection)`);
  L.push(`# ${SQUID_MAIN_CONF} is NOT console-owned by this module (URL-Filter full-file).`);
  L.push(`# Loaded via ${SQUID_CONF_D_INCLUDE} — see the include-order warning in the OS status API.`);
  L.push("");

  if (!needsSslBump || !policy) {
    L.push("# No ENABLED selective/full policy — MITM is OFF. Nothing to enforce:");
    L.push("# no ssl_bump chain, no bump listener, no sslcrtd program is rendered");
    L.push("# and the squid unit is not reloaded (status API reports drift honestly).");
    for (const s of skipped) L.push(`# skipped: ${s.name} — ${s.reason}`);
    L.push(MANAGED_FOOTER);
    L.push("");
    const conf = L.join("\n");
    return {
      conf,
      confHash: sha256_16(conf),
      warnings,
      skipped,
      policy: null,
      needsSslBump: false,
      spliceAcls: [],
    };
  }

  const pid = policy.id;
  const pname = sanitizeComment(policy.name);
  L.push(`# policy: "${pname}" (db id ${pid}) — mode ${policy.mode} · minTLS ${policy.minTlsVersion}`);
  L.push(`# chosen as the first ENABLED selective/full policy (simulated-engine parity, id asc).`);

  // (c) generated-CA requirement — an apply-REFUSING condition (see
  // hardSslRefusal): bumping without an ACTIVE generated CA serves certificates
  // every client rejects. The warning stays in the fragment for honest preview,
  // but the apply plan is refused until the CA is selected/activated.
  if (policy.signingCaId == null) {
    warnings.push(
      `policy "${pname}" has no signing CA (signingCaId null) — bumping needs a generated CA; ` +
        `create one in the PKI module and reference it — apply is REFUSED until an active signing CA is selected`,
    );
    L.push("# WARNING: no signing CA configured (PKI module) — apply is refused until fixed.");
  } else {
    const caLabel = policy.signingCaName ? `"${sanitizeComment(policy.signingCaName, 80)}"` : `id ${policy.signingCaId}`;
    if (policy.signingCaStatus && policy.signingCaStatus !== "active") {
      warnings.push(
        `signing CA ${caLabel} is ${policy.signingCaStatus} — squid will serve certificates the clients reject; ` +
          `activate or replace it in the PKI module — apply is REFUSED until the signing CA is active`,
      );
    }
    warnings.push(
      `MITM re-signs certificates with the GENERATED CA ${caLabel} (PKI module) — clients MUST trust it ` +
        `(export the CA cert from the PKI module and install it as a trusted root) or every bumped session warns`,
    );
    L.push(`# signing CA: ${caLabel} — re-signed certs are only trusted by clients that imported this CA.`);
  }

  // (b) cert-pinning + HSTS honest notes (squid cannot detect either)
  const pinDomains = [...SSL_PINNING_DOMAINS].sort().map((d) => (d.startsWith("*.") ? `.${d.slice(2)}` : d));
  L.push("");
  L.push("# bypass ACLs — splice rules BEFORE bump lines (first-match ssl_bump chain)");
  const domAcl = sslAclName("dom", pid);
  const dstAcl = sslAclName("dst", pid);
  const pinAcl = sslAclName("pin", pid);
  const spliceAcls: string[] = [];

  const rules = inputs.bypassRules
    .filter((r) => r.enabled && r.policyId === policy.id)
    .sort((a, b) => a.id - b.id);
  const domValues: string[] = [];
  const dstValues: string[] = [];
  for (const r of rules) {
    const dom = bypassToDstdomain(r.matchType, r.matchValue);
    const dst = bypassToDst(r.matchType, r.matchValue);
    if (dom) {
      if (!domValues.includes(dom)) domValues.push(dom);
      continue;
    }
    if (dst) {
      if (!dstValues.includes(dst)) dstValues.push(dst);
      continue;
    }
    skipped.push({
      name: `bypass rule #${r.id} (${r.matchType}:${r.matchValue})`,
      reason: "category matchType has no squid ACL representation — replace with explicit domains/wildcards",
    });
    warnings.push(
      `bypass rule #${r.id} (${r.matchType}:${r.matchValue}) is category-based — squid cannot match it; rendered as a comment`,
    );
    L.push(`# skipped bypass rule #${r.id}: category "${r.matchValue}" (no squid representation)`);
  }
  if (domValues.length > 0) {
    L.push(`acl ${domAcl} dstdomain ${domValues.join(" ")}`);
    spliceAcls.push(domAcl);
  }
  if (dstValues.length > 0) {
    L.push(`acl ${dstAcl} dst ${dstValues.join(" ")}`);
    spliceAcls.push(dstAcl);
  }
  if (domValues.length === 0 && dstValues.length === 0) {
    L.push("# (no enabled bypass rules — everything below follows the policy mode)");
  }

  const pinningSplices = policy.certPinningAction === "bypass";
  L.push(`acl ${pinAcl} dstdomain ${pinDomains.join(" ")}`);
  L.push(`acl ${sslAclName("step", pid)} at_step SslBump1`);
  spliceAcls.push(pinAcl);

  L.push("");
  L.push("# ssl_bump chain — evaluated top-down, first match wins (splice > terminate > peek > bump)");
  const bypassAcls = spliceAcls.filter((a) => a !== pinAcl);
  for (const acl of bypassAcls) {
    L.push(`ssl_bump splice ${acl}`);
  }
  if (pinningSplices) {
    L.push(`ssl_bump splice ${pinAcl}   # cert-pinning bypass — no MITM for pinning-sensitive SNIs`);
    warnings.push(
      `certPinningAction=bypass for policy "${pname}": squid cannot DETECT certificate pinning — the sample ` +
        `pinning list (${SSL_PINNING_DOMAINS.join(", ")}) is spliced so pinning clients keep working; ` +
        `any other pinning app may still break against the generated CA`,
    );
  } else {
    L.push(`ssl_bump terminate ${pinAcl}   # cert-pinning block — pinning-sensitive SNIs are FAILED, not MITM'd`);
    warnings.push(
      `certPinningAction=block for policy "${pname}": rendered as ssl_bump terminate — connections to ` +
        `pinning domains FAIL outright (squid cannot distinguish pinning from any other server cert)`,
    );
  }
  if (policy.mode === "selective") {
    L.push(`ssl_bump peek ${sslAclName("step", pid)}   # step 1: learn SNI from the client hello (no MITM yet)`);
  }
  L.push("ssl_bump bump all");

  L.push("");
  L.push("# server-side certificate validation of the UPSTREAM connection");
  if (policy.invalidCertAction === "warn_bypass") {
    L.push("sslproxy_cert_error allow all");
    L.push("# invalidCertAction=warn_bypass — invalid upstream certs are ACCEPTED; squid has no");
    L.push("# warn step, the error is visible only in cache.log / access.log.");
    warnings.push(
      `invalidCertAction=warn_bypass rendered as sslproxy_cert_error allow all — squid has no warn-only step; ` +
        `invalid upstream certificates are accepted and merely logged`,
    );
  } else {
    L.push("sslproxy_cert_error deny all");
    L.push("# invalidCertAction=block — transactions on invalid upstream certificates are terminated.");
  }

  L.push("");
  L.push("# dynamic certificate generation (squid ≥4 binary; legacy helper: ssl_crtd)");
  L.push(`sslcrtd_program ${SSL_CRTD_PROGRAM} -s ${SSL_CRTD_DB_DIR} -M ${SSL_CRTD_DB_SIZE}`);
  warnings.push(
    `sslcrtd certificate cache (${SSL_CRTD_DB_DIR}) is initialized on first apply ` +
      `(${SSL_CRTD_PROGRAM} -c) when missing — apply is refused outright when this squid build lacks ssl-crtd`,
  );

  if (policy.mode === "selective") {
    L.push("");
    L.push("# selective mode: peek (SNI) then bump — splice lines above won for bypass hosts");
  }
  L.push("");
  L.push(`# dedicated ssl-bump listener — :3128 belongs to the URL-Filter module and is NOT modified;`);
  L.push(`# point inspected clients/TPROXY rules at :${SSL_BUMP_PORT} for MITM`);
  L.push(`http_port ${SSL_BUMP_PORT} ssl-bump`);

  L.push("");
  if (skipped.length > 0) {
    L.push(`# skipped (${skipped.length}):`);
    for (const s of skipped) L.push(`#   ${s.name} — ${s.reason}`);
    L.push("");
  }
  L.push(MANAGED_FOOTER);
  L.push("");

  const conf = L.join("\n");
  return { conf, confHash: sha256_16(conf), warnings, skipped, policy, needsSslBump: true, spliceAcls };
}

// ── apply plan ──────────────────────────────────────────────────────────────

export type SslStepKind = "dir" | "backup" | "write" | "init" | "validate" | "reload" | "verify" | "probe";

export interface SslPlanStep {
  step: string;
  cmd: string;
  kind: SslStepKind;
  /** probes / informational — failure recorded, not fatal */
  optional?: boolean;
}

export interface SslFilePlan {
  path: string;
  content: string;
  backup: boolean;
}

export interface SslApplyPlan {
  mode: "exec" | "plan";
  files: SslFilePlan[];
  steps: SslPlanStep[];
  backupDir: string;
  confHash: string;
  warnings: string[];
  skipped: Array<{ name: string; reason: string }>;
  confText: string;
  /** true when there is nothing to enforce (no enabled selective/full policy) */
  empty: boolean;
  guarded: boolean;
  refused: string | null;
  needsSslBump: boolean;
  policyId: number | null;
}

/**
 * Red-line refusals — checked before any exec. Values come from validated
 * columns, but a validator bypass must never reach the fragment or shell.
 *
 * SIGNING-CA CHAIN (audit hard-refusal): a needsSslBump policy without a
 * signing CA (signingCaId null) or with a signing CA that is not "active"
 * would MITM traffic with certificates every client rejects — that is an
 * outage, not a config note, so the apply plan is REFUSED (not warned) until
 * the operator selects an active signing CA in the PKI module.
 */
export function hardSslRefusal(inputs: SslRenderInput): string | null {
  for (const r of inputs.bypassRules) {
    if (/["'\\\s;$`]/.test(r.matchValue)) {
      return `refused: bypass rule #${r.id} matchValue "${r.matchValue}" contains characters squid/shell cannot carry safely — fix the rule first`;
    }
  }
  for (const p of inputs.policies) {
    if (/["'\\\r\n;$`]/.test(p.name)) {
      return `refused: policy id ${p.id} name contains characters that would break the fragment comments — rename it`;
    }
  }
  const { policy, needsSslBump } = effectivePolicy(inputs);
  if (needsSslBump && policy) {
    if (policy.signingCaId == null) {
      return `refused: policy "${sanitizeComment(policy.name)}" (db id ${policy.id}) has no signing CA (signingCaId null) — select an active signing CA in the PKI module before applying`;
    }
    if (policy.signingCaStatus !== "active") {
      const caLabel = policy.signingCaName ? `"${sanitizeComment(policy.signingCaName, 80)}"` : `id ${policy.signingCaId}`;
      return `refused: signing CA ${caLabel} is ${policy.signingCaStatus ?? "unknown"} — select an active signing CA (activate or replace it in the PKI module) before applying`;
    }
  }
  return null;
}

/**
 * Validate-after-stage apply plan:
 *   1. state dir
 *   2. backup the live fragment → SSL_STATE_DIR/backup-<ts>/<abs path>
 *   3. stage the fragment via fs ("write-file" — executed by node fs, not shell)
 *   4. init sslcrtd cache when missing (security_file_certgen -c)
 *   5. `squid -k parse` — validates the LIVE tree AFTER staging, BEFORE reload
 *   6. activate: systemctl start squid (unit inactive) or reload (active) —
 *      only when MITM is required OR a previously installed fragment must be
 *      unloaded; an empty render on a clean host leaves the unit alone
 *   7. verify: is-active + listener probe (:3129, informational)
 *
 * CAPABILITY REFUSAL: needsSslBump && !sslCrtdSupported → plan.refused with an
 * actionable message (honest degradation, spec §6) — no steps are fabricated.
 */
export function buildSslApplyPlan(
  inputs: SslRenderInput,
  facts: Pick<SslOsFacts, "unitState" | "managedFilePresent" | "sslCrtdSupported" | "sslDbPresent">,
  mode: "exec" | "plan",
  ts: string,
  rendered?: SslRenderResult,
): SslApplyPlan {
  const render = rendered ?? renderSslFragment(inputs);
  const backupDir = `${SSL_STATE_DIR}/backup-${ts}`;
  const steps: SslPlanStep[] = [];

  steps.push({ step: "state dir", cmd: `mkdir -p ${SSL_STATE_DIR}`, kind: "dir" });
  if (facts.managedFilePresent) {
    steps.push({
      step: `backup ${SSL_MANAGED_NAME}`,
      cmd: `cp ${SSL_MANAGED_FILE} ${backupDir}${SSL_MANAGED_FILE}`,
      kind: "backup",
    });
  }
  steps.push({ step: `write ${SSL_MANAGED_NAME}`, cmd: `write-file ${SSL_MANAGED_FILE}`, kind: "write" });

  const activate = render.needsSslBump || facts.managedFilePresent;
  if (render.needsSslBump && facts.sslCrtdSupported && facts.sslDbPresent === false) {
    steps.push({
      step: "init sslcrtd cache",
      cmd: `${SSL_CRTD_PROGRAM} -c -s ${SSL_CRTD_DB_DIR} -M ${SSL_CRTD_DB_SIZE}`,
      kind: "init",
    });
  }

  steps.push({ step: "validate config", cmd: "squid -k parse", kind: "validate" });
  if (activate) {
    const startNeeded = facts.unitState !== "active";
    steps.push({
      step: startNeeded ? "start squid" : "reload squid",
      cmd: startNeeded ? "systemctl start squid" : "systemctl reload squid",
      kind: "reload",
    });
    steps.push({ step: "verify unit", cmd: "systemctl is-active squid", kind: "verify" });
    if (render.needsSslBump) {
      steps.push({
        step: "probe bump listener",
        cmd: `ss -ltn '( sport = :${SSL_BUMP_PORT} )'`,
        kind: "probe",
        optional: true,
      });
    }
  }

  const hard = hardSslRefusal(inputs);
  const refused =
    render.needsSslBump && facts.sslCrtdSupported === false
      ? "refused: this squid build lacks ssl-crtd (no --enable-ssl-crtd configure flag and no " +
        `${SSL_CRTD_PROGRAM} / ${SSL_CRTD_LEGACY_BINARY} helper) — install or compile squid with ssl-crtd ` +
        "support, or switch the enabled policy to cert-pinning-bypass-only mode (mode none) before applying"
      : hard;

  return {
    mode,
    files: [{ path: SSL_MANAGED_FILE, content: render.conf, backup: true }],
    steps,
    backupDir,
    confHash: render.confHash,
    warnings: render.warnings,
    skipped: render.skipped,
    confText: render.conf,
    empty: !render.needsSslBump,
    guarded: steps.every((s) => sslStepGuarded(s.cmd)),
    refused,
    needsSslBump: render.needsSslBump,
    policyId: render.policy?.id ?? null,
  };
}

// ── command whitelist (EXACT commands — wafStepGuarded pattern) ─────────────

function isBackupDest(p: string): boolean {
  return p.startsWith(`${SSL_STATE_DIR}/backup-`) && !p.includes("..");
}

/** EXACT-command whitelist for SSL apply — nothing else may execute. */
export function sslStepGuarded(cmd: string): boolean {
  const c = cmd.trim();
  if (!c) return false;
  if (c === "squid -k parse") return true;
  if (c === "squid -v") return true;
  if (c === "systemctl reload squid") return true;
  if (c === "systemctl start squid") return true;
  if (c === "systemctl restart squid") return true;
  if (c === "systemctl is-active squid") return true;
  if (c === `ss -ltn '( sport = :${SSL_BUMP_PORT} )'`) return true;
  if (c === `mkdir -p ${SSL_STATE_DIR}`) return true;
  if (c === `rm -f ${SSL_MANAGED_FILE}`) return true; // rollback path only
  if (c === `ls ${SSL_CRTD_LEGACY_BINARY}`) return true; // capability fallback probe
  if (c === `${SSL_CRTD_PROGRAM} -c -s ${SSL_CRTD_DB_DIR} -M ${SSL_CRTD_DB_SIZE}`) return true;
  // backup cp: managed fragment → SSL_STATE_DIR/backup-<ts>/<same abs path>
  const cpBackup = /^cp (\S+) (\S+)$/.exec(c);
  if (cpBackup) {
    const [, src, dst] = cpBackup;
    if (src === SSL_MANAGED_FILE && isBackupDest(dst) && dst.endsWith(SSL_MANAGED_FILE)) return true;
  }
  // staged writes are flagged in the plan — executed via node fs by the service
  const wf = /^write-file (\S+)$/.exec(c);
  if (wf && wf[1] === SSL_MANAGED_FILE) return true;
  return false;
}

/** Runtime check: backup dirs live in SSL_STATE_DIR and match backup-<ts>. */
export function isSslBackupDir(dir: string): boolean {
  if (!dir.startsWith(`${SSL_STATE_DIR}/`)) return false;
  if (dir.includes("..")) return false;
  return SSL_BACKUP_RE.test(dir.split("/").pop() ?? "");
}

// ── drift (console intent vs OS reality) ────────────────────────────────────

export interface SslDrift {
  inSync: boolean;
  managedByConsole: boolean;
  reasons: string[];
}

/**
 * inSync flips ONLY on (a) live fragment hash vs last applied state,
 * (b) rendered intent vs last applied state, (c) unit state, and (d) ssl-crtd
 * capability (a unit that cannot run the flow is never "in sync").
 */
export function computeSslDrift(
  facts: Pick<
    SslOsFacts,
    "available" | "unitState" | "liveHash" | "managedByConsole" | "sslCrtdSupported"
  > & { stateHash?: string | null },
  renderedHash: string,
  needsSslBump: boolean,
): SslDrift {
  const reasons: string[] = [];
  const stateHash = facts.stateHash ?? null;
  const managedByConsole = Boolean(stateHash && facts.liveHash && stateHash === facts.liveHash);

  if (!facts.available) {
    return { inSync: false, managedByConsole, reasons: ["squid not available on this host"] };
  }
  if (facts.liveHash == null) {
    reasons.push("managed fragment not deployed — apply to OS");
  } else if (!facts.managedByConsole && !managedByConsole) {
    reasons.push("managed fragment changed outside the console (hash differs from last applied)");
  } else if (stateHash !== renderedHash) {
    reasons.push("console config changed since last apply — apply to OS");
  }
  if (needsSslBump && !facts.sslCrtdSupported) {
    reasons.push(
      "squid lacks ssl-crtd — MITM cannot run on this host (install/compile squid with ssl-crtd or use mode none)",
    );
  }
  if (needsSslBump && facts.unitState !== "active") {
    reasons.push(`squid service is ${facts.unitState ?? "unknown"}, expected active`);
  }
  return { inSync: reasons.length === 0, managedByConsole, reasons };
}
