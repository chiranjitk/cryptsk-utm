/**
 * Render the FULL managed squid.conf.
 * Ordering (first-match-wins — this is the include-after-deny-all fix):
 *   1. header + essential stock settings
 *   2. stock ACLs + hygiene denies (!Safe_ports, CONNECT !SSL_ports, manager)
 *   3. ALWAYS_BLOCKED categories (malware, phishing) — unconditional deny
 *      FIRST after the hygiene rules (task mandate; stricter than the
 *      simulated engine, where a custom allow would win)
 *   4. per-policy sections sorted by policy id:
 *      custom allow → custom block → category allow → category block →
 *      warn(deny) → file-type http_reply_access deny → default-allow
 *      (localhost+localnet) when defaultAction=allow
 *   5. `http_access deny all` (catch-all; BEFORE the conf.d include)
 *   6. safe-search rewrite block (when enforced)
 *   7. `include /etc/squid/conf.d/*.conf` LAST
 */
export function renderSquidConf(input: UfRenderInput): UfRenderResult {
  const L: string[] = [];
  const warnings: string[] = [];
  const policyHashes: Record<number, string> = {};
  const enabled = [...input.policies].filter((p) => p.enabled).sort((a, b) => a.id - b.id);
  const disabled = input.policies.filter((p) => !p.enabled).sort((a, b) => a.id - b.id);

  const rulesByPolicy = new Map<number, UfCategoryRuleInput[]>();
  for (const r of input.categoryRules) {
    if (!rulesByPolicy.has(r.policyId)) rulesByPolicy.set(r.policyId, []);
    rulesByPolicy.get(r.policyId)!.push(r);
  }
  const listsByPolicy = new Map<number, UfCustomListInput[]>();
  for (const l of input.customLists) {
    if (!listsByPolicy.has(l.policyId)) listsByPolicy.set(l.policyId, []);
    listsByPolicy.get(l.policyId)!.push(l);
  }

  let allowCount = 0;
  let blockCount = 0;
  let fileTypesCount = 0;

  // ── 1. header ──
  L.push(MANAGED_HEADER);
  L.push("# Managed file: /etc/squid/squid.conf (FULL-FILE management — Debian's stock");
  L.push("# conf ends `http_access deny all` BEFORE `include /etc/squid/conf.d/*.conf`,");
  L.push("# so fragment rules would be dead; the console renders the complete file).");
  L.push(
    `# policies: ${enabled.length ? enabled.map((p) => `#${p.id} ${sanitizeComment(p.name)}`).join(" · ") : "(none enabled)"}`,
  );

  // ── 2. essential stock settings + ACLs + hygiene ──
  L.push("");
  L.push("# ── essential stock settings (Debian squid 6.x defaults, no cache_dir) ──");
  L.push("http_port 3128");
  L.push("access_log daemon:/var/log/squid/access.log squid");
  L.push("coredump_dir /var/spool/squid");
  L.push("");
  L.push("# ── stock ACLs ──");
  L.push(...STOCK_ACLS);
  L.push("");
  L.push("# ── port hygiene (before ANY policy rule) ──");
  L.push("http_access deny !Safe_ports");
  L.push("http_access deny CONNECT !SSL_ports");
  L.push("# cache manager: loopback only");
  L.push("http_access allow localhost manager");
  L.push("http_access deny manager");

  // ── 3. ALWAYS_BLOCKED first ──
  const alwaysCats = URL_CATEGORIES.filter((c) => ALWAYS_BLOCKED.has(c));
  L.push("");
  L.push(`# ── always-blocked categories (unconditional — reason: ${REASON.category}/ALWAYS_BLOCKED) ──`);
  for (const cat of alwaysCats) {
    const domains = catalogDomainsFor(cat);
    if (domains.length === 0) continue;
    L.push(`acl ${aclCategoryName(cat)} dstdomain ${domains.map((d) => `.${d}`).join(" ")}`);
    L.push(`http_access deny ${aclCategoryName(cat)}`);
    warnings.push(
      `category '${cat}' is always blocked (ALWAYS_BLOCKED) — rendered FIRST after port hygiene; a custom allow-list entry cannot override it on the appliance (stricter than the simulated test engine)`,
    );
  }

  // ── 4a. category ACLs referenced by enabled rules (union of sample domains) ──
  const usedCats = new Set<string>();
  const aggregatedSeen = new Set<string>();
  for (const p of enabled) {
    for (const r of rulesByPolicy.get(p.id) ?? []) {
      if (!r.enabled || !URL_CATEGORIES.includes(r.category as UrlFilterCategory)) continue;
      usedCats.add(r.category);
      if (r.listSource === "aggregated" && !aggregatedSeen.has(r.category)) {
        aggregatedSeen.add(r.category);
        warnings.push(
          `category '${r.category}' uses an aggregated feed which is not installed — sample-domain subset enforced (catalog: ${catalogDomainsFor(r.category).length} domains)`,
        );
      }
    }
  }
  const catAclLines: string[] = [];
  const orderedCats = URL_CATEGORIES.filter((c) => usedCats.has(c) || ALWAYS_BLOCKED.has(c));
  for (const cat of orderedCats) {
    const domains = catalogDomainsFor(cat);
    if (domains.length === 0) continue;
    catAclLines.push(`acl ${aclCategoryName(cat)} dstdomain ${domains.map((d) => `.${d}`).join(" ")}`);
  }
  if (catAclLines.length > 0 && enabled.length > 0) {
    L.push("");
    L.push("# ── category ACLs (catalog sample domains; aggregated feed not installed — honest subset) ──");
    L.push(...catAclLines);
  }

  // ── 4b. per-policy sections ──
  let safesearchNeeded = false;
  for (const p of disabled) {
    L.push("");
    L.push(`# policy ${p.id}: ${sanitizeComment(p.name)} — DISABLED in console, not rendered`);
  }
  for (const p of enabled) {
    const section: string[] = [];
    section.push("");
    section.push(`# policy ${p.id}: ${sanitizeComment(p.name)} (defaultAction=${p.defaultAction})`);
    section.push(`# reason waterfall mirrors the simulated test engine (${REASON.custom_allow} > ${REASON.custom_block} > ${REASON.category} > ${REASON.file_type} > ${REASON.default})`);

    const lists = (listsByPolicy.get(p.id) ?? []).sort((a, b) =>
      a.listType === b.listType
        ? a.matchType === b.matchType
          ? a.value.localeCompare(b.value)
          : a.matchType.localeCompare(b.matchType)
        : a.listType.localeCompare(b.listType),
    );

    // custom allow acls + rules (reason: custom_allow)
    const allowDom = lists
      .filter((l) => l.listType === "allow" && l.matchType !== "url")
      .map((l) => customListToDstdomain(l.matchType, l.value)!)
      .sort();
    const allowUrl = lists.filter((l) => l.listType === "allow" && l.matchType === "url").map((l) => l.value).sort();
    const blockDom = lists
      .filter((l) => l.listType === "block" && l.matchType !== "url")
      .map((l) => customListToDstdomain(l.matchType, l.value)!)
      .sort();
    const blockUrl = lists.filter((l) => l.listType === "block" && l.matchType === "url").map((l) => l.value).sort();
    if (allowDom.length > INLINE_ACL_CAP) {
      warnings.push(
        `policy '#${p.id} ${sanitizeComment(p.name)}' custom allow list has ${allowDom.length} entries — still inlined (cap ${INLINE_ACL_CAP} warned, external file feeds are v2)`,
      );
    }
    if (allowDom.length > 0) {
      section.push(`acl ${aclName("allow", p.id, "dom")} dstdomain ${allowDom.join(" ")}`);
      allowCount += allowDom.length;
    }
    if (allowUrl.length > 0) {
      section.push(`acl ${aclName("allow", p.id, "url")} url_regex -i ${allowUrl.map(customListToUrlRegex).join(" ")}`);
      allowCount += allowUrl.length;
    }
    if (allowDom.length > 0 || allowUrl.length > 0) {
      section.push(`# reason: ${REASON.custom_allow}`);
      if (allowDom.length > 0) section.push(`http_access allow ${aclName("allow", p.id, "dom")}`);
      if (allowUrl.length > 0) section.push(`http_access allow ${aclName("allow", p.id, "url")}`);
    }

    // custom block acls + rules (reason: custom_block)
    if (blockDom.length > INLINE_ACL_CAP) {
      warnings.push(
        `policy '#${p.id} ${sanitizeComment(p.name)}' custom block list has ${blockDom.length} entries — still inlined (cap ${INLINE_ACL_CAP} warned, external file feeds are v2)`,
      );
    }
    if (blockDom.length > 0) {
      section.push(`acl ${aclName("block", p.id, "dom")} dstdomain ${blockDom.join(" ")}`);
      blockCount += blockDom.length;
    }
    if (blockUrl.length > 0) {
      section.push(`acl ${aclName("block", p.id, "url")} url_regex -i ${blockUrl.map(customListToUrlRegex).join(" ")}`);
      blockCount += blockUrl.length;
    }
    if (blockDom.length > 0 || blockUrl.length > 0) {
      section.push(`# reason: ${REASON.custom_block}`);
      if (blockDom.length > 0) section.push(`http_access deny ${aclName("block", p.id, "dom")}`);
      if (blockUrl.length > 0) section.push(`http_access deny ${aclName("block", p.id, "url")}`);
    }

    // category rules (reason: category) — allow before block before warn
    const rules = (rulesByPolicy.get(p.id) ?? []).filter(
      (r) => r.enabled && URL_CATEGORIES.includes(r.category as UrlFilterCategory),
    );
    const catOrder = (a: UfCategoryRuleInput, b: UfCategoryRuleInput) =>
      URL_CATEGORIES.indexOf(a.category as UrlFilterCategory) - URL_CATEGORIES.indexOf(b.category as UrlFilterCategory);
    const catAllows = rules.filter((r) => r.action === "allow").sort(catOrder);
    const catBlocks = rules.filter((r) => r.action === "block").sort(catOrder);
    const catWarns = rules.filter((r) => r.action === "warn").sort(catOrder);
    if (catAllows.length > 0 || catBlocks.length > 0 || catWarns.length > 0) {
      section.push(`# reason: ${REASON.category} (allow rules render before block rules)`);
      for (const r of catAllows) section.push(`http_access allow ${aclCategoryName(r.category)}`);
      for (const r of catBlocks) section.push(`http_access deny ${aclCategoryName(r.category)}`);
      for (const r of catWarns) {
        section.push(`# category '${r.category}' warn rendered as deny (squid ACLs have no log-only warn action — reason: category)`);
        section.push(`http_access deny ${aclCategoryName(r.category)}`);
      }
    }

    // file types (reason: file_type — reply-phase)
    const filesRe = fileTypesRegex(p.fileTypesBlocked ?? []);
    if (filesRe) {
      section.push(`acl ${aclFilesName(p.id)} urlpath_regex -i ${filesRe}`);
      section.push(`# reason: ${REASON.file_type} (http_reply_access — evaluated on the server reply)`);
      section.push(`http_reply_access deny ${aclFilesName(p.id)}`);
      fileTypesCount += 1;
    }

    // default action (reason: default)
    if (p.defaultAction === "allow") {
      section.push(`# reason: ${REASON.default} — defaultAction allow: management + LAN browsing permitted beyond this point`);
      section.push("http_access allow localhost");
      section.push("http_access allow localnet");
    } else {
      section.push(`# reason: ${REASON.default} — defaultAction block: trailing http_access deny all enforces it`);
    }

    // safe search (reason: safe_search — HTTP URL rewrite; HTTPS needs bump)
    if (p.safeSearchEnforce) {
      safesearchNeeded = true;
      if (!p.httpsInspection) {
        warnings.push(
          `policy '#${p.id} ${sanitizeComment(p.name)}' safeSearchEnforce: safe-search is enforced for HTTP only; HTTPS requires ssl-bump (not enabled)`,
        );
      }
    }
    if (p.httpsInspection) {
      warnings.push(
        `policy '#${p.id} ${sanitizeComment(p.name)}' httpsInspection: ssl-bump requires the ssl-crtd build — httpsInspection noted, not enforced (v1)`,
      );
    }
    if (p.transparentProxy) {
      warnings.push(
        `policy '#${p.id} ${sanitizeComment(p.name)}' transparentProxy: transparent mode requires an nft TPROXY redirect — explicit proxy enforced on :3128`,
      );
    }

    policyHashes[p.id] = sha256_16(section.join("\n") + "\n");
    L.push(...section);
  }

  // ── 5. catch-all deny (BEFORE the conf.d include) ──
  L.push("");
  L.push(`# ── catch-all (reason: ${REASON.default}) — first-match-wins ends here ──`);
  L.push("http_access deny all");

  // ── 6. safe-search rewrite block ──
  if (safesearchNeeded) {
    L.push("");
    L.push(`# ── SafeSearch enforcement (HTTP URL rewrite — reason: ${REASON.safe_search}) ──`);
    L.push("# HTTPS searches pass through untouched without ssl-bump (see warnings).");
    L.push(`url_rewrite_program ${SAFESSEARCH_SCRIPT}`);
    L.push("url_rewrite_children 5 startup=1 idle=1");
    L.push(`acl utm_search dstdomain ${SEARCH_ENGINE_DOMAINS.map((d) => `.${d}`).join(" ")}`);
    L.push("url_rewrite_access allow utm_search");
    L.push("url_rewrite_access deny all");
  }

  // ── 7. conf.d include LAST (stock: only debian.conf lives there) ──
  L.push("");
  L.push("# Debian conf.d include — kept LAST (after the catch-all deny), stock contents only.");
  L.push(`include ${SQUID_CONF_D_GLOB}`);
  L.push("");

  const conf = L.join("\n");
  return {
    conf,
    confHash: sha256_16(conf),
    policyHashes,
    safesearchScript: safesearchNeeded ? renderSafesearchScript() : null,
    warnings,
    managedCounts: { allow: allowCount, block: blockCount, categories: catAclLines.length, fileTypes: fileTypesCount },
  };
}

// ── drift ───────────────────────────────────────────────────────────────────

export interface UfDriftFacts {
  available: boolean;
  managedFilePresent: boolean;
  liveHash: string | null;
  running: boolean;
  port3128Bound: boolean;
}

export interface UfDrift {
  inSync: boolean;
  driftReasons: string[];
}

/**
 * Console intent vs OS reality. ONLY the file hash and the unit state flip
 * inSync — the port probe is surfaced as an informational reason (a bound
 * listener is checked again at verify time during apply).
 */
export function computeSquidDrift(facts: UfDriftFacts, renderedHash: string): UfDrift {
  const reasons: string[] = [];
  if (!facts.available) {
    return { inSync: false, driftReasons: ["squid binary not available on this host"] };
  }
  if (!facts.managedFilePresent || facts.liveHash === null) {
    reasons.push("managed squid.conf not deployed — apply to OS");
  } else if (facts.liveHash !== renderedHash) {
    reasons.push(`OS hash ${facts.liveHash} ≠ rendered hash ${renderedHash} — apply to OS`);
  }
  if (!facts.running) {
    reasons.push("squid.service is not active — apply (re)starts it");
  }
  if (!facts.port3128Bound) {
    reasons.push("port 3128 not bound (informational — squid listens only once running)");
  }
  // ONLY file hash + unit state flip inSync — the port reason is informational.
  const hashOk = facts.managedFilePresent && facts.liveHash === renderedHash;
  return { inSync: hashOk && facts.running, driftReasons: reasons };
}

// ── command whitelist (red lines) ───────────────────────────────────────────

/**
 * EXACT/prefix whitelist for every executed URL-filter step.
 * Anything else — and anything with shell chaining metacharacters — refuses.
 */
export function squidStepGuarded(cmd: string): boolean {
  const c = cmd.trim();
  if (!c) return false;
  if (/[;&|`]|\$\(/.test(c)) return false; // no chaining, ever
  if (c.startsWith("squid -k parse")) return true;
  if (c === "squid -k reconfigure") return true;
  if (c.startsWith("install -m 0644 /var/lib/console/url-filter/")) return true;
  if (c.startsWith("install -m 0755 /var/lib/console/url-filter/")) return true;
  if (c.startsWith("cp /etc/squid/squid.conf ")) return true;
  if (c === "systemctl restart squid") return true;
  if (c === "systemctl is-active squid") return true;
  if (c.startsWith("ss -ltn")) return true;
  if (c.startsWith("rm -f /var/lib/console/url-filter/stage")) return true;
  return false;
}

// ── apply plan ──────────────────────────────────────────────────────────────

export interface UfPlanStep {
  step: string;
  cmd: string;
  kind: "backup" | "validate" | "install" | "reload" | "verify" | "cleanup" | "restore";
}

export interface UfPlanFile {
  path: string;
  content: string;
  mode: number; // 0o644 conf, 0o755 rewriter script
}

export interface UfApplyPlan {
  mode: "exec" | "plan";
  steps: UfPlanStep[];
  rollbackSteps: UfPlanStep[];
  files: UfPlanFile[];
  backupDir: string;
  confText: string;
  confHash: string;
  warnings: string[];
  skipped: Array<{ name: string; reason: string }>;
  /** true when squid was running before apply — reload vs restart decision */
  wasRunning: boolean;
  guarded: boolean;
  /** red-line refusal (hardSslRefusal pattern) — executor must not run when set */
  refused: string | null;
}

/**
 * Red-line refusal (hardSslRefusal mirror) — checked before any exec.
 * Custom-list values are read back from the DB and interpolated into
 * dstdomain / url_regex ACL tokens; a validator bypass (or a value smuggled
 * past the create schema by a legacy/import path) must never reach the
 * renderer — each value is re-validated against the create-time grammar and
 * shell/squid-token-breaking characters are refused outright.
 */
export function hardUfRefusal(input: UfRenderInput): string | null {
  for (const l of input.customLists) {
    if (/["'\\\s;$`]/.test(l.value)) {
      return `refused: custom list #policy ${l.policyId} ${l.listType} ${l.matchType}:"${l.value}" contains characters squid/shell cannot carry safely — fix the list entry first`;
    }
    if (!valueMatchesMatchType(l.matchType, l.value)) {
      return `refused: custom list #policy ${l.policyId} ${l.listType} ${l.matchType}:"${l.value}" no longer matches the ${l.matchType} grammar — fix the list entry before applying`;
    }
  }
  return null;
}

/**
 * Validate-first apply plan (ha/os.ts pattern, full-file management):
 *   1. backup live conf → backup-<ts>/squid.conf (cp, guarded)
 *   2. stage rendered conf (fs write, pinned path; install sets the mode)
 *   3. `squid -k parse -f <stage>` — validate the STAGE, never the live file
 *   4. `install -m 0644 <stage> /etc/squid/squid.conf` — atomic install
 *   5. install safesearch rewriter (0755) when rendered
 *   6. reload: `squid -k reconfigure` when running, else `systemctl restart squid`
 *   7. verify: is-active + `squid -k parse -f live` + port probe
 *   8. cleanup stage files
 * On failure of 3–7 the executor restores backup-<ts>/squid.conf (fs),
 * revalidates the restored live file and restarts squid (rollbackSteps).
 */
export function buildSquidApplyPlan(
  input: UfRenderInput,
  facts: UfDriftFacts,
  opts: { mode: "exec" | "plan"; ts: string },
  rendered?: UfRenderResult,
): UfApplyPlan {
  const render = rendered ?? renderSquidConf(input);
  const backupDir = `${UF_STATE_DIR}/backup-${opts.ts}`;
  const files: UfPlanFile[] = [{ path: UF_STAGE_FILE, content: render.conf, mode: 0o644 }];
  if (render.safesearchScript) files.push({ path: UF_STAGE_SCRIPT, content: render.safesearchScript, mode: 0o755 });

  const steps: UfPlanStep[] = [
    { step: "backup live conf", cmd: `cp ${SQUID_CONF} ${backupDir}/squid.conf`, kind: "backup" },
    { step: "validate stage", cmd: `squid -k parse -f ${UF_STAGE_FILE}`, kind: "validate" },
    { step: "install conf", cmd: `install -m 0644 ${UF_STAGE_FILE} ${SQUID_CONF}`, kind: "install" },
  ];
  if (render.safesearchScript) {
    steps.push({ step: "install safesearch rewriter", cmd: `install -m 0755 ${UF_STAGE_SCRIPT} ${SAFESSEARCH_SCRIPT}`, kind: "install" });
  }
  steps.push({
    step: facts.running ? "reload squid" : "start squid",
    cmd: facts.running ? "squid -k reconfigure" : "systemctl restart squid",
    kind: "reload",
  });
  steps.push(
    { step: "verify unit", cmd: "systemctl is-active squid", kind: "verify" },
    { step: "verify live conf", cmd: `squid -k parse -f ${SQUID_CONF}`, kind: "verify" },
    { step: "verify port 3128", cmd: "ss -ltn '( sport = :3128 )'", kind: "verify" },
    { step: "cleanup stage", cmd: `rm -f ${UF_STATE_DIR}/stage`, kind: "cleanup" },
  );

  const rollbackSteps: UfPlanStep[] = [
    { step: "restore backup", cmd: `fs:restore ${backupDir}/squid.conf -> ${SQUID_CONF}`, kind: "restore" },
    { step: "revalidate restored conf", cmd: `squid -k parse -f ${SQUID_CONF}`, kind: "validate" },
    { step: "restart squid on restored conf", cmd: "systemctl restart squid", kind: "reload" },
  ];

  const skipped: Array<{ name: string; reason: string }> = [];
  for (const p of input.policies.filter((p) => !p.enabled)) {
    skipped.push({ name: `policy ${p.id}: ${sanitizeComment(p.name)}`, reason: "disabled in console — not rendered" });
  }

  return {
    mode: opts.mode,
    steps,
    rollbackSteps,
    files,
    backupDir,
    confText: render.conf,
    confHash: render.confHash,
    warnings: render.warnings,
    skipped,
    wasRunning: facts.running,
    guarded: steps.every((s) => squidStepGuarded(s.cmd)),
    refused: hardUfRefusal(input),
  };
}
