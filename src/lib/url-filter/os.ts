// ── hash ────────────────────────────────────────────────────────────────────

/** sha256[:16] — drift compares the LIVE file hash with the rendered hash. */
export function sha256_16(text: string): string {
  return createHash("sha256").update(text, "utf8").digest("hex").slice(0, 16);
}

// ── pure helpers ────────────────────────────────────────────────────────────

/** Escape regex metacharacters for url_regex / urlpath_regex values. */
export function escapeRegex(v: string): string {
  return v.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/** One-line comment-safe policy name (no newlines, bounded length). */
export function sanitizeComment(name: string, max = 64): string {
  const safe = name.replace(/[\r\n]+/g, " ").trim().slice(0, max);
  return safe || "unnamed";
}

/**
 * Custom-list value → squid acl token.
 *   domain   → `.value`        (dstdomain leading dot covers subdomains)
 *   wildcard → `.base`         (`*.base` is exactly dstdomain `.base`)
 *   url      → null here (rendered as a separate url_regex acl)
 */
export function customListToDstdomain(matchType: string, value: string): string | null {
  if (matchType === "url") return null;
  if (matchType === "wildcard") return value.startsWith("*.") ? `.${value.slice(2)}` : `.${value}`;
  return `.${value}`;
}

/** url matchType → url_regex pattern anchored at the scheme (escaped body). */
export function customListToUrlRegex(value: string): string {
  return `^${escapeRegex(value)}`;
}

/** fileTypesBlocked → one urlpath_regex alternation, e.g. `\.(exe|bat)$`. */
export function fileTypesRegex(exts: string[]): string | null {
  const clean = [...new Set(exts.map((e) => e.trim().toLowerCase()))].filter((e) => /^[a-z0-9]{1,10}$/.test(e)).sort();
  if (clean.length === 0) return null;
  return `\\.(${clean.join("|")})$`;
}

/** category → sorted catalog sample domains (inverted SAMPLE_DOMAIN_CATEGORIES). */
export function catalogDomainsFor(category: string): string[] {
  return Object.entries(SAMPLE_DOMAIN_CATEGORIES)
    .filter(([, cat]) => cat === category)
    .map(([domain]) => domain)
    .sort();
}

/**
 * testUrl()'s reason enum — the RENDERING ORACLE. Every rendered rule group is
 * annotated with the reason a simulated test would report for the same class
 * of request, so GUI expectations and appliance behavior stay comparable.
 * (Type-only import — erased at runtime, keeps this module pure.)
 */
const REASON: Record<UrlFilterReason, UrlFilterReason> = {
  custom_allow: "custom_allow",
  custom_block: "custom_block",
  category: "category",
  safe_search: "safe_search",
  file_type: "file_type",
  default: "default",
};

const ACL_ID_RE = /^[a-z0-9_]+$/;

/** ACL name for a policy custom list — deterministic + squid-name-safe. */
export function aclName(kind: "allow" | "block", policyId: number, matchType: "dom" | "url"): string {
  const name = `utm_${kind}_${policyId}_${matchType}`;
  if (!ACL_ID_RE.test(name)) throw new Error(`unsafe acl name: ${name}`);
  return name;
}

export function aclCategoryName(category: string): string {
  const name = `utm_cat_${category}`;
  if (!ACL_ID_RE.test(name)) throw new Error(`unsafe acl name: ${name}`);
  return name;
}

export function aclFilesName(policyId: number): string {
  const name = `utm_files_${policyId}`;
  if (!ACL_ID_RE.test(name)) throw new Error(`unsafe acl name: ${name}`);
  return name;
}

// ── safesearch rewriter (second managed file — rendered content) ────────────

/**
 * Tiny POSIX url_rewrite_program: forces safe-search query params on search
 * engines. HTTPS URLs pass through untouched (needs ssl-bump); DuckDuckGo /
 * Brave enforce via cookies/POST — only query-parameter forcing is possible,
 * which the warning in the conf documents honestly.
 */
export function renderSafesearchScript(): string {
  const L: string[] = [
    "#!/bin/sh",
    MANAGED_HEADER,
    `# Managed: ${SAFESSEARCH_SCRIPT} — squid url_rewrite_program (SafeSearch, HTTP only).`,
    '# stdin lines: "<url> <ip>/<ident> [<method>]" — stdout: rewritten line.',
    "# Honest limits: HTTPS passes through untouched (needs ssl-bump); DuckDuckGo",
    "# and Brave enforce SafeSearch via cookies/POST — only query-parameter",
    "# forcing (safe=active / adlt=strict) is possible from a URL rewriter.",
    "while read -r url rest; do",
    '  case "$url" in',
    '    *google.*/search*)',
    "      url=$(printf '%s\\n' \"$url\" | sed 's/&safe=off//g; s/?safe=off/?/g')",
    '      case "$url" in',
    '        *\\?*) url="${url}&safe=active" ;;',
    '        *)    url="${url}?safe=active" ;;',
    "      esac",
    "      ;;",
    '    *bing.com/search*)',
    "      url=$(printf '%s\\n' \"$url\" | sed 's/&adlt=off//g')",
    '      case "$url" in',
    '        *\\?*) url="${url}&adlt=strict" ;;',
    '        *)    url="${url}?adlt=strict" ;;',
    "      esac",
    "      ;;",
    '    *yahoo.com/search*)',
    '      case "$url" in',
    '        *\\?*) url="${url}&vm=r" ;;',
    '        *)    url="${url}?vm=r" ;;',
    "      esac",
    "      ;;",
    "  esac",
    "  printf '%s %s\\n' \"$url\" \"$rest\"",
    "done",
    "",
  ];
  return L.join("\n");
}

// ── renderer (pure — unit tested, byte-stable) ──────────────────────────────

export interface UfRenderResult {
  /** complete squid.conf text (ends with newline) */
  conf: string;
  /** sha256[:16] of conf */
  confHash: string;
  /** per-policy rendered section hash (status endpoint / drift hints) */
  policyHashes: Record<number, string>;
  /** safesearch rewrite script content when any enabled policy enforces it */
  safesearchScript: string | null;
  /** honest renderer warnings (aggregated feeds, warn-as-deny, https, tproxy, caps) */
  warnings: string[];
  /** number of custom values rendered + category acls + file-type policies */
  managedCounts: { allow: number; block: number; categories: number; fileTypes: number };
}

