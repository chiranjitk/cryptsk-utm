/**
 * URL-Filter OS integration (GUI ↔ Squid 6.13, Debian 13) — PURE core:
 * deterministic squid.conf renderer, command whitelist, apply-plan builder and
 * drift computation. NO db / exec imports here — everything touching db, fs or
 * child_process lives in os-service.ts (mirrors dns/os.ts + ha/os.ts).
 *
 * WHY FULL-FILE MANAGEMENT (keepalived-style, not a conf.d fragment):
 *   Debian's stock /etc/squid/squid.conf ends its access section with
 *   `http_access deny all` BEFORE the trailing
 *   `include /etc/squid/conf.d/*.conf` (line ~1621). A fragment delivering
 *   `http_access allow/deny …` would therefore be parsed AFTER the catch-all
 *   deny — first-match-wins makes every fragment rule dead. The console thus
 *   renders the COMPLETE squid.conf: essential stock settings + stock ACLs,
 *   then console policy rules, ending `http_access deny all` and keeping the
 *   conf.d include LAST (only debian.conf lives there).
 *
 * Rendering oracle: the simulated decision engine `testUrl()` (service.ts)
 * with its reason enum — custom_allow > custom_block > ALWAYS_BLOCKED >
 * category(allow|block|warn) > safe_search(HTTP rewrite) > file_type >
 * default. Each rendered rule group is annotated with the matching reason.
 *
 * Honest limitations surfaced as warnings (never silently dropped):
 *   • aggregated category feeds are not installed → catalog sample-domain
 *     subset is enforced;
 *   • warn is rendered as deny (squid ACLs have no log-only warn action);
 *   • safe-search rewrites HTTP URLs only (HTTPS needs ssl-bump; the Debian
 *     squid build may lack ssl-crtd → httpsInspection is noted, not enforced);
 *   • transparentProxy still runs as an explicit proxy on :3128 (TPROXY
 *     redirect is an nftables concern outside this module).
 */

