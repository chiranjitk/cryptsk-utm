/**
 * HA OS layer (M10 / spec §1.13) — the pure core that bridges the console HA
 * config to the real Keepalived appliance:
 *
 *   • renderKeepalivedConf  deterministic /etc/keepalived/keepalived.conf text
 *   • parseKeepalivedConf   extract vrrp_instance facts from an OS conf
 *   • computeHaDrift        console intent vs OS reality
 *   • buildHaApplyPlan      step list (validate-first, backup, install, restart, verify)
 *   • haStepGuarded         EXACT-command whitelist — no other exec path
 *
 * SAFETY CONTRACT (hard red lines, enforced in code):
 *   • the VRRP interface must NEVER be the WAN/ens32 uplink — a VIP there
 *     would re-route the management path;
 *   • `keepalived -t` must pass BEFORE the live conf is touched (validate-first);
 *   • the previous conf is backed up to HA_STATE_DIR and restored automatically
 *     when the restart/verify step fails;
 *   • execution itself lives in the API route and only runs when
 *     CONSOLE_OS_APPLY=1 (gate) — plan preview is always available.
 */

import { fnv1aHash } from "@/lib/dns/os";

// ── constants ───────────────────────────────────────────────────────────────

export const HA_INSTANCE_NAME = "VI_CONSOLE";
export const KEEPALIVED_CONF = "/etc/keepalived/keepalived.conf";
export const KEEPALIVED_STAGE = "/etc/keepalived/keepalived.conf.console-staged";
export const HA_VALIDATE_TMP = "/tmp/console-ha-validate.conf";
export const HA_STATE_DIR = "/var/lib/console/ha";
/** Console-owned backups: keepalived.conf.backup-<ts> */
export const HA_BACKUP_RE = /^keepalived\.conf\.backup-[\w.-]+$/;

/** Interfaces the console must never manage VRRP on (WAN uplink red line). */
export function haForbiddenIfaces(): string[] {
  const env = process.env.CONSOLE_PROTECTED_IFACES;
  if (env && env.trim()) return env.split(",").map((s) => s.trim()).filter(Boolean);
  return ["ens32"];
}

// ── inputs ──────────────────────────────────────────────────────────────────

/** Minimal keepalived-bearing slice of the HaConfig row. */
export type HaKeepalivedInput = {
  enabled: boolean;
  role: string; // disabled | active | standby
  priority: number;
  virtualIp: string | null; // CIDR, e.g. 10.99.99.253/32
  ifaceName: string;
  peerIp: string | null;
  trackedInterfaces: string[];
  failAfterSec: number;
  holdDownSec: number;
  vrid: number;
  advertIntSec: number;
  authPass: string | null;
  preempt: boolean;
};

export type KeepalivedRenderCtx = {
  /** router_id for global_defs (defaults to a stable literal) */
  routerId: string;
  /** primary IPv4 on ifaceName — required for unicast mode when peerIp is set */
  localIfaceIp?: string | null;
};

export type HaOsFacts = {
  available: boolean; // keepalived binary present
  serviceState: string | null; // systemctl is-active keepalived
  confText: string | null; // current /etc/keepalived/keepalived.conf
  confHash: string | null;
  osConfHash: string | null; // last console-applied hash (DB)
  conntrackdState: string | null;
  vrrpState: "master" | "backup" | "fault" | null; // journalctl-derived
  vipPresent: boolean;
  localIfaceIp: string | null;
};

// ── renderer ────────────────────────────────────────────────────────────────

/**
 * Deterministic keepalived.conf for the console-managed pair.
 * Mapping (M10 §5.1 → keepalived semantics):
 *   role active   → state MASTER (initial hint; election still priority-based)
 *   role standby  → state BACKUP
 *   holdDownSec   → preempt_delay (failback hold-down)
 *   preempt=false → nopreempt (standby keeps MASTER after recovery)
 *   failAfterSec  → documented via advert_int: VRRP detection ≈ 3×advert + skew
 *   peerIp+localIP→ unicast_src_ip/unicast_peer (required on cloud/NFV where
 *                    VRRP multicast is not delivered)
 */
export function renderKeepalivedConf(cfg: HaKeepalivedInput, ctx: KeepalivedRenderCtx): string {
  const L: string[] = [];
  L.push("! Generated by Cryptsk Console — do not edit by hand; changes are overwritten.");
  L.push(`! console section: ha · instance: ${HA_INSTANCE_NAME}`);
  L.push("global_defs {");
  L.push(`\trouter_id ${sanitizeRouterId(ctx.routerId)}`);
  L.push("\tenable_script_security");
  L.push("}");

  if (!cfg.enabled || cfg.role === "disabled") {
    L.push("! HA disabled in console — no vrrp_instance rendered.");
    return L.join("\n") + "\n";
  }

  const vipAddr = cfg.virtualIp?.split("/")[0] ?? null;
  const useUnicast = Boolean(cfg.peerIp && ctx.localIfaceIp && vipAddr);

  L.push("");
  L.push(`vrrp_instance ${HA_INSTANCE_NAME} {`);
  L.push(`\tstate ${cfg.role === "active" ? "MASTER" : "BACKUP"}`);
  L.push(`\tinterface ${cfg.ifaceName}`);
  L.push(`\tvirtual_router_id ${cfg.vrid}`);
  L.push(`\tpriority ${cfg.priority}`);
  L.push(`\tadvert_int ${cfg.advertIntSec}`);
  if (cfg.authPass) {
    L.push("\tauthentication {");
    L.push("\t\tauth_type PASS");
    L.push(`\t\tauth_pass ${cfg.authPass}`);
    L.push("\t}");
  }
  if (useUnicast) {
    L.push(`\tunicast_src_ip ${ctx.localIfaceIp}`);
  }
  if (!cfg.preempt) {
    L.push("\tnopreempt");
  } else if (cfg.holdDownSec > 0) {
    if (cfg.role === "active") {
      // keepalived clears preempt_delay when the initial state is MASTER
      // (config-test warning: "preempt delay will not work with initial
      // state MASTER") — render an explicit note instead of a broken knob.
      L.push("\t! preempt_delay ignored: initial state MASTER (hold-down applies after failback from BACKUP)");
    } else {
      L.push(`\tpreempt_delay ${cfg.holdDownSec}`);
    }
  }
  if (useUnicast && cfg.peerIp) {
    L.push("\tunicast_peer {");
    L.push(`\t\t${cfg.peerIp}`);
    L.push("\t}");
  }
  if (cfg.virtualIp) {
    L.push("\tvirtual_ipaddress {");
    L.push(`\t\t${cfg.virtualIp} dev ${cfg.ifaceName}`);
    L.push("\t}");
  }
  if (cfg.trackedInterfaces.length > 0) {
    L.push("\ttrack_interface {");
    for (const t of cfg.trackedInterfaces) L.push(`\t\t${t}`);
    L.push("\t}");
  }
  L.push("}");
  return L.join("\n") + "\n";
}

function sanitizeRouterId(id: string): string {
  const safe = id.replace(/[^A-Za-z0-9_-]/g, "").slice(0, 64);
  return safe || "UTM-CONSOLE";
}

/** Hash of the rendered conf — stored on apply, compared on every status poll. */
export function haConfHash(confText: string): string {
  return fnv1aHash(confText);
}

// ── parser ──────────────────────────────────────────────────────────────────

export type ParsedVrrpInstance = {
  name: string;
  iface: string | null;
  vrid: number | null;
  priority: number | null;
  state: string | null; // MASTER | BACKUP as written
  vips: string[]; // address[/prefix] literals
  trackInterfaces: string[];
};

/** Extract vrrp_instance blocks from any keepalived.conf text (best effort). */
export function parseKeepalivedConf(confText: string): ParsedVrrpInstance[] {
  const out: ParsedVrrpInstance[] = [];
  const lines = confText.split("\n");

  // 1) capture each vrrp_instance { … } block with brace-depth tracking
  let cur: string[] | null = null;
  let depth = 0;
  for (const raw of lines) {
    const line = raw.trim();
    if (cur === null) {
      const open = line.match(/^vrrp_instance\s+(\S+)\s*\{$/);
      if (open) {
        cur = [open[1]];
        depth = 1;
      }
      continue;
    }
    // inside an instance block
    depth += (line.match(/\{/g)?.length ?? 0) - (line.match(/\}/g)?.length ?? 0);
    if (depth <= 0) {
      out.push(...parseInstanceBlock(cur));
      cur = null;
      depth = 0;
      continue;
    }
    cur.push(line);
  }
  if (cur) out.push(...parseInstanceBlock(cur));
  return out;
}

function parseInstanceBlock(block: string[]): ParsedVrrpInstance[] {
  const inst: ParsedVrrpInstance = {
    name: block[0],
    iface: null,
    vrid: null,
    priority: null,
    state: null,
    vips: [],
    trackInterfaces: [],
  };
  let section: "none" | "vip" | "track" = "none";
  for (const line of block.slice(1)) {
    const isComment = line.startsWith("!") || line.startsWith("#");
    if (isComment || !line) continue;
    if (line === "virtual_ipaddress {") {
      section = "vip";
      continue;
    }
    if (line === "track_interface {") {
      section = "track";
      continue;
    }
    if (line === "}") {
      section = "none";
      continue;
    }
    if (section === "vip") {
      const vip = line.split(/\s+/)[0];
      if (vip) inst.vips.push(vip);
      continue;
    }
    if (section === "track") {
      if (/^[A-Za-z0-9._@:-]+$/.test(line)) inst.trackInterfaces.push(line);
      continue;
    }
    const kv = line.match(/^(interface|virtual_router_id|priority|state)\s+(\S+)$/);
    if (kv) {
      if (kv[1] === "interface") inst.iface = kv[2];
      if (kv[1] === "virtual_router_id") inst.vrid = Number(kv[2]) || null;
      if (kv[1] === "priority") inst.priority = Number(kv[2]) || null;
      if (kv[1] === "state") inst.state = kv[2];
    }
  }
  return [inst];
}

// ── drift ───────────────────────────────────────────────────────────────────

export type HaDrift = {
  inSync: boolean;
  managedByConsole: boolean; // conf hash matches the last applied hash
  reasons: string[];
};

/**
 * Console intent vs OS reality. When HA is disabled in the console we do NOT
 * demand a conf without instances — an operator-managed instance (like the
 * bootstrap VI_TEST) may legitimately exist; we only report it as unmanaged.
 */
export function computeHaDrift(cfg: HaKeepalivedInput, facts: HaOsFacts): HaDrift {
  const reasons: string[] = [];
  const managedByConsole = Boolean(
    facts.osConfHash && facts.confHash && facts.osConfHash === facts.confHash,
  );

  if (!facts.available) {
    return { inSync: false, managedByConsole, reasons: ["keepalived binary not available on host"] };
  }
  if (!facts.confText || !facts.confHash) {
    return { inSync: false, managedByConsole, reasons: ["keepalived.conf missing on host"] };
  }
  if (!managedByConsole) {
    reasons.push("keepalived.conf is not console-managed (hash mismatch with last applied)");
  }

  if (!cfg.enabled || cfg.role === "disabled") {
    return {
      inSync: reasons.length === 0,
      managedByConsole,
      reasons,
    };
  }

  const parsed = parseKeepalivedConf(facts.confText);
  const inst = parsed.find((p) => p.name === HA_INSTANCE_NAME);
  if (!inst) {
    reasons.push(`no ${HA_INSTANCE_NAME} instance in keepalived.conf`);
  } else {
    const vipAddr = cfg.virtualIp?.split("/")[0] ?? null;
    if (inst.iface !== cfg.ifaceName) reasons.push(`instance iface ${inst.iface ?? "?"} ≠ console ${cfg.ifaceName}`);
    if (inst.vrid !== cfg.vrid) reasons.push(`instance VRID ${inst.vrid ?? "?"} ≠ console ${cfg.vrid}`);
    if (inst.priority !== cfg.priority) reasons.push(`instance priority ${inst.priority ?? "?"} ≠ console ${cfg.priority}`);
    if (vipAddr && !inst.vips.some((v) => v.split("/")[0] === vipAddr)) {
      reasons.push(`VIP ${vipAddr} not present in instance`);
    }
    for (const t of cfg.trackedInterfaces) {
      if (!inst.trackInterfaces.includes(t)) reasons.push(`tracked interface ${t} missing in instance`);
    }
  }

  if (facts.serviceState !== "active") {
    reasons.push(`keepalived service is ${facts.serviceState ?? "unknown"}, expected active`);
  }
  if (cfg.virtualIp && !facts.vipPresent) {
    reasons.push(`VIP ${cfg.virtualIp.split("/")[0]} not assigned to ${cfg.ifaceName} (VRRP not in MASTER or iface down)`);
  }

  return { inSync: reasons.length === 0, managedByConsole, reasons };
}

// ── apply plan ──────────────────────────────────────────────────────────────

export type HaPlanStep = { step: string; cmd: string };
export type HaApplyPlan = {
  mode: "exec" | "plan";
  steps: HaPlanStep[];
  backupFile: string;
  stageFile: string;
  confText: string;
  confHash: string;
  guarded: boolean; // every command passed the whitelist
  refused: string | null; // hard-refusal reason (forbidden iface, disabled, …)
};

/**
 * Validate-first apply plan:
 *   1. mkdir state dir
 *   2. backup live conf (timestamped, console-owned dir)
 *   3. stage rendered conf
 *   4. keepalived -t on the STAGE file (never on the live conf)
 *   5. install stage → live  (atomic mv on the same filesystem)
 *   6. systemctl restart keepalived
 *   7. verify: is-active + conf hash still ours
 * On failure of 6/7 the route restores the backup and restarts again.
 */
export function buildHaApplyPlan(
  cfg: HaKeepalivedInput,
  ctx: KeepalivedRenderCtx,
  mode: "exec" | "plan",
  ts: string,
): HaApplyPlan {
  const confText = renderKeepalivedConf(cfg, ctx);
  const backupFile = `${HA_STATE_DIR}/keepalived.conf.backup-${ts}`;
  const steps: HaPlanStep[] = [
    { step: "state dir", cmd: `mkdir -p ${HA_STATE_DIR}` },
    { step: "backup live conf", cmd: `cp ${KEEPALIVED_CONF} ${backupFile}` },
    { step: "stage conf", cmd: `install -m 0644 /dev/null ${KEEPALIVED_STAGE}` },
    { step: "write stage", cmd: `write-file ${KEEPALIVED_STAGE}` },
    { step: "validate stage", cmd: `keepalived -t -f ${KEEPALIVED_STAGE}` },
    { step: "install conf", cmd: `install -m 0644 ${KEEPALIVED_STAGE} ${KEEPALIVED_CONF}` },
    { step: "restart", cmd: "systemctl restart keepalived" },
    { step: "verify", cmd: "systemctl is-active keepalived" },
    { step: "cleanup stage", cmd: `rm -f ${KEEPALIVED_STAGE}` },
  ];

  const refused = hardRefusal(cfg);
  return {
    mode,
    steps,
    backupFile,
    stageFile: KEEPALIVED_STAGE,
    confText,
    confHash: haConfHash(confText),
    guarded: steps.every((s) => haStepGuarded(s.cmd)),
    refused,
  };
}

/** Hard red-line refusals — checked before any exec. */
export function hardRefusal(cfg: HaKeepalivedInput): string | null {
  if (haForbiddenIfaces().includes(cfg.ifaceName)) {
    return `refused: interface '${cfg.ifaceName}' is a protected WAN uplink — console never manages VRRP on it`;
  }
  for (const t of cfg.trackedInterfaces) {
    if (haForbiddenIfaces().includes(t)) {
      return `refused: tracked interface '${t}' is a protected WAN uplink — remove it from track_interface`;
    }
  }
  if (cfg.enabled && cfg.role !== "disabled" && !cfg.virtualIp) {
    return "refused: HA is enabled but no virtual IP is configured — nothing to apply";
  }
  return null;
}

// ── command whitelist (dnsStepGuarded pattern) ──────────────────────────────

/** EXACT-command whitelist for HA apply — nothing else may execute. */
export function haStepGuarded(cmd: string): boolean {
  const c = cmd.trim();
  if (!c) return false;
  if (c === `mkdir -p ${HA_STATE_DIR}`) return true;
  if (c.startsWith(`cp ${KEEPALIVED_CONF} ${HA_STATE_DIR}/keepalived.conf.backup-`)) return true;
  if (c === `install -m 0644 /dev/null ${KEEPALIVED_STAGE}`) return true;
  if (c === `write-file ${KEEPALIVED_STAGE}`) return true;
  if (c === `keepalived -t -f ${KEEPALIVED_STAGE}`) return true;
  if (c === `keepalived -t -f ${HA_VALIDATE_TMP}`) return true; // validate-only endpoint
  if (c === `install -m 0644 ${KEEPALIVED_STAGE} ${KEEPALIVED_CONF}`) return true;
  if (c === "systemctl restart keepalived") return true;
  if (c === "systemctl is-active keepalived") return true;
  if (c === `rm -f ${KEEPALIVED_STAGE}`) return true;
  return false;
}

/** Runtime check used by the route: the backup file must live in HA_STATE_DIR and match the naming scheme. */
export function isHaBackupPath(file: string): boolean {
  if (!file.startsWith(`${HA_STATE_DIR}/`)) return false;
  if (file.includes("..")) return false; // traversal guard
  return HA_BACKUP_RE.test(file.split("/").pop() ?? "");
}

// ── keepalived -t interpretation ───────────────────────────────────────

export type KeepalivedTestResult = {
  ok: boolean;
  hasErrors: boolean;
  warnings: string[];
  detail: string;
};

/**
 * `keepalived -t` exits non-zero for WARNINGS too (exit code = problem count),
 * but warnings are self-correcting ("... - clearing") while errors mean the
 * config cannot run. A test is a hard failure only when output contains an
 * error / exiting line; warnings alone pass with the warning text surfaced.
 */
export function interpretKeepalivedTest(output: string, execOk: boolean): KeepalivedTestResult {
  const lines = output.split("\n").map((l) => l.trim()).filter(Boolean);
  const warnings = lines.filter((l) => /warning/i.test(l));
  const errorLines = lines.filter((l) => /\berror\b/i.test(l) || /exiting/i.test(l));
  const hasErrors = errorLines.length > 0 || (!execOk && lines.length === 0);
  return {
    ok: !hasErrors,
    hasErrors,
    warnings,
    detail:
      errorLines.length > 0
        ? errorLines.join(" | ").slice(0, 400)
        : warnings.length > 0
          ? `keepalived -t passed with ${warnings.length} warning(s): ${warnings.join(" | ").slice(0, 300)}`
          : execOk
            ? "keepalived -t passed (rc=0)"
            : "keepalived -t failed with no output (exec error)",
  };
}

// ── journal parsing (status enrichment) ─────────────────────────────────────

/**
 * Derive the live VRRP state from keepalived journal lines:
 *   "(VI_X): Entering MASTER STATE" → master, BACKUP → backup, FAULT → fault.
 * The LAST Entering/FAULT line for ANY instance wins (single-instance pairs
 * in Phase 1; multi-instance clusters show the most recent transition).
 */
export function parseVrrpStateFromJournal(journal: string): "master" | "backup" | "fault" | null {
  const re = /Entering\s+(MASTER|BACKUP|FAULT)\s+STATE/i;
  let state: "master" | "backup" | "fault" | null = null;
  for (const line of journal.split("\n")) {
    const m = line.match(re);
    if (m) {
      const s = m[1].toUpperCase();
      state = s === "MASTER" ? "master" : s === "BACKUP" ? "backup" : "fault";
    }
  }
  return state;
}
